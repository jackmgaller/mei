# ---- tiles

class Tiler:
    """Cuts an RGB image into 8x8 tiles, maps each to its best palette, shares repeats (and
    mirror images). Tile 0 is empty (transparent)."""

    def __init__(self, palettes, limit=1024):
        self.pals = palettes                       # [[None, rgb x 15]]
        self.limit = limit
        self.tiles = [np.zeros((8, 8), np.uint8)]
        self.index = {self.tiles[0].tobytes(): (0, 0)}
        self.cols = [np.array([c for c in p[1:]], np.int32) for p in palettes]

    def _fit(self, rgb, alpha):
        best = None
        for pi, cols in enumerate(self.cols):
            d = ((rgb[:, :, None, :].astype(np.int32) - cols[None, None, :, :]) ** 2).sum(axis=3)
            idx = d.argmin(axis=2)
            err = d.min(axis=2)[alpha].sum()
            if best is None or err < best[0]:
                best = (err, pi, (idx + 1).astype(np.uint8))
        _, pi, idx = best
        idx[~alpha] = 0
        return pi, idx

    def add(self, rgb, alpha):
        if not alpha.any():
            return 0
        pi, idx = self._fit(rgb, alpha)
        for flip, t in ((0, idx), (0x4000, idx[:, ::-1]), (0x8000, idx[::-1, :]),
                        (0xC000, idx[::-1, ::-1])):
            k = t.tobytes()
            if k in self.index and self.index[k][1] == pi:
                return self.index[k][0] | flip | (pi << 10)
        n = len(self.tiles)
        if n >= self.limit:
            raise SystemExit('more than %d tiles' % self.limit)
        self.tiles.append(idx)
        self.index[idx.tobytes()] = (n, pi)
        return n | (pi << 10)

    def cut(self, img, alpha, mw, mh):
        """The map (mh x mw entries) of an image of up to (mh * 8) x (mw * 8) pixels."""
        h, w = alpha.shape
        m = np.zeros((mh, mw), np.uint16)
        for ty in range(h // 8):
            for tx in range(w // 8):
                sl = (slice(ty * 8, ty * 8 + 8), slice(tx * 8, tx * 8 + 8))
                m[ty, tx] = self.add(img[sl], alpha[sl])
        return m

    def atlas(self):
        """The 4-bit atlas bytes: tile t at column t % 32, row t // 32; only the rows used."""
        rows = (len(self.tiles) + 31) // 32
        a = np.zeros((rows * 8, 256), np.uint8)
        for t, idx in enumerate(self.tiles):
            a[(t // 32) * 8:(t // 32) * 8 + 8, (t % 32) * 8:(t % 32) * 8 + 8] = idx
        return ((a[:, 0::2] & 15) | ((a[:, 1::2] & 15) << 4)).astype(np.uint8).tobytes()

    def pal_blob(self):
        out = b''
        for p in self.pals:
            cols = [0] + [c15(c) for c in p[1:]]
            cols += [0] * (16 - len(cols))
            out += struct.pack('<16H', *cols)
        return out


# ---- drawing helpers

class Canvas:
    def __init__(self, w, h):
        self.img = Image.new('RGBA', (w, h), (0, 0, 0, 0))
        self.d = ImageDraw.Draw(self.img)
        self.d.fontmode = '1'                      # no antialiasing: palette colours only

    def rect(self, x0, y0, x1, y1, c):
        """Fills x0..x1-1, y0..y1-1."""
        if x1 > x0 and y1 > y0:
            self.d.rectangle([x0, y0, x1 - 1, y1 - 1], fill=c + (255,))

    def line(self, pts, c, w=1):
        self.d.line(pts, fill=c + (255,), width=w)

    def poly(self, pts, c):
        self.d.polygon(pts, fill=c + (255,))

    def ellipse(self, x0, y0, x1, y1, c):
        self.d.ellipse([x0, y0, x1 - 1, y1 - 1], fill=c + (255,))

    def text(self, x, y, s, font, c, anchor='la'):
        self.d.text((x, y), s, font=font, fill=c + (255,), anchor=anchor)

    def arrays(self):
        a = np.asarray(self.img)
        return a[:, :, :3].copy(), a[:, :, 3] > 127


def font(path, size):
    return ImageFont.truetype(path, size)


