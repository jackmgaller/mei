def build_hall(preview):
    cv, pals = draw_hall()
    rgb, alpha = cv.arrays()
    t = Tiler(pals, limit=1024)
    m = np.zeros((32, 64), np.uint16)
    m[:HALL_H // 8] = t.cut(rgb, alpha, 64, HALL_H // 8)
    if preview:
        cv.img.save(os.path.join(preview, 'stage_hall.png'))
        render_map(t, m, 8, os.path.join(preview, 'stage_hall_tiles.png'))
    return t, m


