def hud_frame():
    """The bezels around the bars, the timer and the meters, with their insides transparent (the
    fills are polygons drawn under BG0's frame... no: over it; the frame sits behind the HUD's
    polygons and in front of the mechs, PLN_PRIO)."""
    W, H = 320, 240
    img = big(W, H)
    dr = ImageDraw.Draw(img)
    P = PALS['hud']

    def S(v):
        return v * SS

    def bezel(x, y, w, h, slant, flip):
        """A slanted chrome bezel 2 px around (x, y, w, h)."""
        def pts(x0, y0, x1, y1, sl):
            if not flip:
                return [(S(x0) + S(sl), S(y0)), (S(x1), S(y0)), (S(x1) - S(sl), S(y1)), (S(x0), S(y1))]
            return [(S(x0), S(y0)), (S(x1) - S(sl), S(y0)), (S(x1), S(y1)), (S(x0) + S(sl), S(y1))]
        dr.polygon(pts(x - 4, y - 3, x + w + 4, y + h + 3, slant + 2), fill=P[0] + (255,))
        dr.polygon(pts(x - 3, y - 2, x + w + 3, y + h + 2, slant + 1), fill=P[5] + (255,))
        dr.polygon(pts(x - 3, y - 2, x + w + 3, y + h // 2, slant + 1), fill=P[6] + (255,))
        dr.polygon(pts(x - 1, y - 1, x + w + 1, y + h + 1, slant), fill=P[0] + (255,))
        dr.polygon(pts(x, y, x + w, y + h, slant), fill=(0, 0, 0, 0))

    h = HUD
    for side in (0, 1):
        x = h['bar_x0'] if side == 0 else 320 - h['bar_x0'] - h['bar_w']
        bezel(x, h['bar_y'], h['bar_w'], h['bar_h'], 4, side == 1)
        # a tab under the bar for the name
        tx = x if side == 0 else x + h['bar_w'] - 70
        dr.polygon([(S(tx), S(h['bar_y'] + h['bar_h'] + 3)), (S(tx + 70), S(h['bar_y'] + h['bar_h'] + 3)),
                    (S(tx + 66), S(h['bar_y'] + h['bar_h'] + 12)), (S(tx + 4), S(h['bar_y'] + h['bar_h'] + 12))],
                   fill=P[1] + (255,))
        mx = h['meter_x0'] if side == 0 else 320 - h['meter_x0'] - h['meter_w']
        bezel(mx, h['meter_y'], h['meter_w'], h['meter_h'], 3, side == 1)
        # the icon's socket
        ix = mx - 22 if side == 0 else mx + h['meter_w'] + 4
        dr.ellipse([S(ix - 1), S(h['meter_y'] - 6), S(ix + 19), S(h['meter_y'] + 14)], fill=P[0] + (255,))
        dr.ellipse([S(ix), S(h['meter_y'] - 5), S(ix + 18), S(h['meter_y'] + 13)], fill=P[5] + (255,))
    # the timer capsule
    tx, ty, tw, th = h['timer_x'], h['timer_y'], h['timer_w'], h['timer_h']
    dr.rounded_rectangle([S(tx - 4), S(ty - 3), S(tx + tw + 4), S(ty + th + 3)], radius=S(7), fill=P[0] + (255,))
    dr.rounded_rectangle([S(tx - 3), S(ty - 2), S(tx + tw + 3), S(ty + th + 2)], radius=S(6), fill=P[6] + (255,))
    dr.rounded_rectangle([S(tx - 1), S(ty), S(tx + tw + 1), S(ty + th)], radius=S(5), fill=P[0] + (255,))
    dr.rounded_rectangle([S(tx), S(ty + 1), S(tx + tw), S(ty + th - 1)], radius=S(4), fill=(0, 0, 0, 0))
    return down(img)


