# effects (white, tinted at draw): levels 1..15 of the grey ramp

def fx_glow(d):
    y, x = np.mgrid[0:d, 0:d]
    r = np.hypot(x - (d - 1) / 2, y - (d - 1) / 2) / (d / 2)
    v = np.clip(1 - r, 0, 1) ** 1.6
    return np.where(v > 0.03, np.clip(np.round(v * 15), 1, 15), 0).astype(np.uint8)


def fx_spark(d):
    y, x = np.mgrid[0:d, 0:d]
    cx = (d - 1) / 2
    dx, dy = np.abs(x - cx) / (d / 2), np.abs(y - cx) / (d / 2)
    star = np.clip(1 - (dx * 6 + dy) , 0, 1) + np.clip(1 - (dy * 6 + dx), 0, 1)
    diag = np.clip(1 - (np.abs(dx - dy) * 5 + (dx + dy) * 0.9), 0, 1) * 0.6
    core = np.clip(1 - np.hypot(dx, dy) * 2.5, 0, 1)
    v = np.clip(star + diag + core, 0, 1)
    return np.where(v > 0.04, np.clip(np.round(v * 15), 1, 15), 0).astype(np.uint8)


def fx_ring(d):
    y, x = np.mgrid[0:d, 0:d]
    r = np.hypot(x - (d - 1) / 2, y - (d - 1) / 2) / (d / 2)
    v = np.clip(1 - np.abs(r - 0.8) * 7, 0, 1)
    return np.where(v > 0.04, np.clip(np.round(v * 15), 1, 15), 0).astype(np.uint8)


def fx_wave(w, h):
    """The Hero's ground wave: a crescent of light, its bright edge to the right (the way it
    travels; mirrored at draw for the other way)."""
    y, x = np.mgrid[0:h, 0:w]
    u = x / (w - 1)
    vy = (y - (h - 1) / 2) / (h / 2)
    edge = 0.78 - 0.5 * vy ** 2          # the front edge's u at height vy
    t = np.clip(1 - (edge - u) / 0.7, 0, 1) * (u <= edge)
    t = t ** 1.5 * np.clip(1 - np.abs(vy) ** 3, 0, 1)
    front = np.clip(1 - np.abs(u - edge) * 18, 0, 1) * np.clip(1 - np.abs(vy) ** 4, 0, 1)
    v = np.clip(t * 0.8 + front, 0, 1)
    return np.where(v > 0.04, np.clip(np.round(v * 15), 1, 15), 0).astype(np.uint8)


def fx_streak(w, h):
    y, x = np.mgrid[0:h, 0:w]
    u = x / (w - 1)
    vy = np.abs(y - (h - 1) / 2) / (h / 2)
    v = np.clip(u, 0, 1) * np.clip(1 - vy, 0, 1)
    return np.where(v > 0.04, np.clip(np.round(v * 15), 1, 15), 0).astype(np.uint8)


