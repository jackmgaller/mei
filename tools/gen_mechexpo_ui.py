def ttf_font(path, size, keep=None, mono_digits=False, track=0):
    glyphs, h, line = meifont.ttf_glyphs(path, size, first=32, count=95, mono_digits=mono_digits,
                                         track=track)
    if keep is not None:
        glyphs = [(img, adv) if chr(32 + i) in keep else (None, adv) for i, (img, adv) in enumerate(glyphs)]
    top, bot = h, 0
    for img, adv in glyphs:
        if img is not None and img.any():
            rows = np.where(img.any(axis=1))[0]
            top, bot = min(top, rows.min()), max(bot, rows.max())
    glyphs = [(img[top:bot + 1] if img is not None else None, adv) for img, adv in glyphs]
    nh = bot + 1 - top
    return glyphs, nh, nh + max(2, line - h)


def place_font(sheet, glyphs, h, line, name, akr):
    row = sheet.used() + 1 if sheet.used() else 0
    f = meifont.build_font(glyphs, h, line, slot=sheet.slot, palette=PAL_FONT, row=row,
                           colours=meifont.default_colours(15, None, (10, 16, 40)),
                           include_texels=False)
    n = f.atlas.shape[0]
    sheet.img[row:row + n] = np.maximum(sheet.img[row:row + n], f.atlas)
    sheet.x, sheet.y, sheet.shelf = 0, row + n, 0
    with open(os.path.join(ART, 'ui_font_%s.fnt' % name), 'wb') as fh:
        fh.write(f.blob())
    akr.append('embed FONT_%s: Font = "art/ui_font_%s.fnt"' % (name.upper(), name))
    return f


