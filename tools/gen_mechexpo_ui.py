def quantize(img, pal, alpha_cut=110):
    """RGBA image -> palette indices (1..15, 0 where transparent), nearest colour."""
    a = np.asarray(img.convert('RGBA')).astype(np.int32)
    cols = np.array(pal, np.int32)
    d = ((a[:, :, None, :3] - cols[None, None, :, :]) ** 2).sum(axis=3)
    idx = (d.argmin(axis=2) + 1).astype(np.uint8)
    idx[a[:, :, 3] < alpha_cut] = 0
    return idx


class Sheet:
    """A 256 x 256 4-bit texture slot, filled on shelves."""

    def __init__(self, slot):
        self.slot = slot
        self.img = np.zeros((256, 256), np.uint8)
        self.x = self.y = self.shelf = 0
        self.rects = []

    def place(self, name, idx, gap=1):
        h, w = idx.shape
        if self.x + w > 255:
            self.x, self.y, self.shelf = 0, self.y + self.shelf + gap, 0
        if self.y + h > 255:
            raise SystemExit('slot %d is full' % self.slot)
        u, v = self.x, self.y
        self.img[v:v + h, u:u + w] = np.maximum(self.img[v:v + h, u:u + w], idx)
        self.x += w + gap
        self.shelf = max(self.shelf, h)
        self.rects.append((name, u, v, w, h))
        return u, v

    def newline(self):
        if self.x:
            self.x, self.y, self.shelf = 0, self.y + self.shelf + 1, 0

    def used(self):
        return self.y + self.shelf

    def blob(self):
        t = self.img[:self.used()]
        return ((t[:, 0::2] & 15) | ((t[:, 1::2] & 15) << 4)).astype(np.uint8).tobytes()

    def preview(self, pal, path):
        p = [(40, 0, 60)] + list(pal)
        img = np.array([[p[i] for i in row] for row in self.img[:self.used()]], np.uint8)
        Image.fromarray(img).resize((512, img.shape[0] * 2), Image.NEAREST).save(path)


