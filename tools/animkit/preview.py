"""`mei_anim.py preview`: a move drawn by Mei, frame by frame, as the game draws it (the cart's
anim.akr and pack, the data exported for this move), from the side with its boxes, laid out
as a contact sheet."""
import csv
from pathlib import Path
import shutil

from kitcore import native
from .export import export, MECHS, MOVES
from .move import Move, MARKS
from .rig import AnimError

ROOT = Path(__file__).resolve().parents[2]
CART = ROOT/'carts'/'mechexpo'
FONT_W = 8


def enum_name(mech):
    """A mech's variant in anim.akr's enum Mech: 'hero' Hero, 'twin_a' TwinA."""
    return ''.join(w.capitalize() for w in mech.split('_'))


def cart_source(mech, mv, length, keys, phases, marks, camera, boxes=True, ground=True, title=''):
    """The preview cart: frame f drawn on tick f, labelled. keys: the key frames; phases:
    (startup, active) or None; marks: per frame bits."""
    key_list = ', '.join(str(k) for k in keys) or '0'
    mark_list = ', '.join(str(m) for m in marks)
    ex, ey, ez = camera
    st, ac = phases or (-1, -1)
    return f'''// Generated by tools/mei_anim.py preview.
cart "Anim preview"
import "anim.akr"
import "depth.akr"

const KEYS: [{max(len(keys), 1)}]s32 = [{key_list}]
const MARKS: [{length}]u32 = [{mark_list}]
const MARK_NAMES: [{len(MARKS)}]*u8 = [{', '.join('"' + n + '"' for n in sorted(MARKS, key=MARKS.get))}]
var tick: s32
var root_x: fixed              // the root's travel so far (anim_root), so the mech moves as in the fight

fn init() {{
    assets_load()
    render_depth(true)
    render_perspective(true)
}}

fn draw() {{
    let f = min(tick, {length - 1})
    cls(0x5C4E44)
    camera_clip(0.5, 200.0)
    camera(vec3({ex:.3f}, {ey:.3f}, {ez:.3f}), 0.0)
    {'draw_ground()' if ground else ''}
    anim_draw(Mech.{enum_name(mech)}, Mv.{mv}, fixed(f), anim_place(vec2(root_x, 0.0), 1))
    let cpu = anim_cpu
    {f'anim_draw_boxes(Mech.{enum_name(mech)}, Mv.{mv}, f, vec2(root_x, 0.0), 1)' if boxes else ''}
    text(4, 4, "{title}", 0xFFFFFF)
    var x = text_int(4, 228, f, 0xFFFFFF)
    var key = false
    for i in 0..len(KEYS) {{ if KEYS[i] == f {{ key = true }} }}
    if key {{ text(x + 4, 228, "KEY", 0x40E0FF) }}
    if f < {st} {{ text(x + 36, 228, "startup", 0xC0C0C0) }}
    else if f < {st + ac} {{ text(x + 36, 228, "ACTIVE", 0x4040FF) }}
    else if {st} >= 0 {{ text(x + 36, 228, "recovery", 0xC0C0C0) }}
    let m = MARKS[f]
    var y = 16
    for i in 0..len(MARK_NAMES) {{
        if (m & ((1 << i) as u32)) != 0 {{
            text(4, y, MARK_NAMES[i], 0x60FF60)
            y += 10
        }}
    }}
    text_int(264, 228, cpu, 0x909090)
    if tick < {length - 1} {{ root_x += anim_root(Mech.{enum_name(mech)}, Mv.{mv}, f).x }}
    tick += 1
}}

// The floor (y = 0) as a line with metre ticks, under the mech.
fn draw_ground() {{
    let a = project_point(vec3(-40.0, 0.0, 0.0))
    let b = project_point(vec3(40.0, 0.0, 0.0))
    line(a.x, a.y, b.x, b.y, 0x9A9A9A)
    for i in -12..24 {{
        let p = project_point(vec3(fixed(i), 0.0, 0.0))
        var h = 2
        if i == 0 {{ h = 6 }}
        line(p.x, p.y, p.x, p.y + h, 0x9A9A9A)
    }}
}}
'''


def tools_ok(compiler, runner):
    native.require('/arguments/tools', [compiler, runner], 'Build them with make B=DIR DIR/meic DIR/mei-headless, '
                   'and pass --build-dir DIR.', AnimError)


def mech_of(move):
    name = move.rig.name
    if name not in MECHS:
        raise AnimError('/rig', f'The rig {name!r} is not one of the cart\'s mechs ({", ".join(MECHS)}).')
    return name


def stage(out, move_path, as_move=None, anims=None, extra=()):
    """Exports the cart's moves with this one (and extra (path, mech, move)s) in their places,
    into out with a copy of anim.akr. Returns (move, mech, mv)."""
    move = Move(move_path, None, as_move)
    mech = mech_of(move)
    mv = as_move or move.name
    if mv not in MOVES:
        raise AnimError('/arguments', f'{mv!r} is not in the move list; pass --as MOVE to preview it in a move\'s place.')
    out.mkdir(parents=True, exist_ok=True)
    over = {(mech, mv): move_path}
    for path, m2, mv2 in extra:
        over[(m2, mv2)] = path
    export(anims or CART/'anims', CART, out, override=over)
    shutil.copy(CART/'anim.akr', out/'anim.akr')
    return move, mech, mv


def preview(move_path, out, compiler, runner, as_move=None, every=None, columns=6, boxes=True, distance=15.0,
            anims=None):
    """Renders every frame of the move and a contact sheet. Returns the report."""
    tools_ok(compiler, runner)
    out = Path(out).resolve()
    move, mech, mv = stage(out, move_path, as_move, anims)
    keys = [k[0] for k in move.pose_keys]
    ph = (move.phases['startup'], move.phases['active']) if move.phases else None
    # the camera: from the side the game sees (the mech faces +x, the camera on -Z), framing the
    # mech's reach
    camera = (2.5+move.root_travel(move.length)[0]/2, 7.0, -distance)
    title = f'{mech.upper()} {mv.upper()}'
    (out/'preview.akr').write_text(cart_source(mech, mv, move.length, keys, ph, move.marks, camera, boxes, True, title))
    frames_dir = out/'frames'
    shutil.rmtree(frames_dir, ignore_errors=True)
    frames_dir.mkdir()
    native.run([compiler, '-I', CART, out/'preview.akr', '-o', out/'preview.mei'], '/preview', error=AnimError)
    native.run([runner, out/'preview.mei', '--frames', str(move.length), '--dump-every', '1', frames_dir/'f',
                '--gpu-stats', out/'gpu.csv'], '/preview', timeout=120, error=AnimError)
    shots = sorted(frames_dir.glob('f*.ppm'))
    if len(shots) < move.length:
        raise AnimError('/preview', f'The runner wrote {len(shots)} frames of {move.length}.')
    images = [native.read_ppm(p, '/preview', AnimError) for p in shots[:move.length]]
    every = every or max(1, (move.length+23)//24)
    chosen = sorted(set(range(0, move.length, every)) | set(keys) |
                    ({move.phases['startup'], move.phases['startup']+move.phases['active']-1} if move.phases else set()))
    chosen = [f for f in chosen if f < move.length]
    sheet = native.contact_sheet([images[f] for f in chosen], columns)
    (out/'contact.png').write_bytes(sheet)
    for f, img in enumerate(images):
        (frames_dir/f'frame_{f:03d}.png').write_bytes(native.png_bytes(native.WIDTH, native.HEIGHT, img))
    for p in shots:
        p.unlink()
    with (out/'gpu.csv').open() as stream:
        rows = list(csv.DictReader(stream))
    cpu = [int(r['cpu_cycles']) for r in rows if 'cpu_cycles' in r]
    gpu = [int(r['gpu_cycles']) for r in rows if 'gpu_cycles' in r]
    return {'ok': True, 'move': f'{mech}/{mv}', 'length': move.length, 'keys': keys, 'output': str(out),
            'contact': str(out/'contact.png'), 'frames': str(frames_dir), 'sheet_frames': chosen,
            'cost': {'cpu_max': max(cpu, default=None), 'gpu_max': max(gpu, default=None),
                     'budget': native.frame_budgets()}, 'warnings': move.warnings}
