#!/usr/bin/env python3
"""Generates Mech Expo 2000's particle sprites (fx.akr's): white and grey sprites the effects
tint and blend, in texture slot 11 with their own grey ramp in 4-bit palette 192 (mx-fx's share
of the cart's palettes is 192-195; the model pack counts up from 0, mx-menus has 196-199).

Writes, in carts/mechexpo/:
  art/fx_particles.tex   slot 11's texels (4-bit, 256 wide, only the rows used)
  art/fx_particles.pal   the palette: 0 transparent, 1-15 a grey ramp (17 to 255)
  fx_art.akr             the embeds, fx_art_load() and the rectangles (FXP_*: u, v, w, h)

The sprites: a glow with a hot core, the hit's starburst, a soft dot, a twinkle star, the impact flare (a star with an
anamorphic streak, 1999 lens-flare style), a thin ring, the shield's hexagon, two smoke puffs, a
flattened dust puff, a speed streak, a chevron, a bubble, two electric arcs and eight frames of
a spinning metal shard (shaded: lit edge, body, dark edge; drawn opaque and tinted).

python3 tools/gen_mechexpo_fx.py [--preview DIR]
"""
import math, os, struct, sys
import numpy as np
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CART = os.path.join(ROOT, 'carts', 'mechexpo')
ART = os.path.join(CART, 'art')
HEADER = '// Generated by tools/gen_mechexpo_fx.py - do not edit.'
SLOT_FXP = 11
PAL_FXP = 192           # 4-bit palette 192 (colours 3072-3087); 193-195 are kept for more
SS = 4                  # supersampling of drawn shapes


def levels(v, cut=0.04):
    """0..1 floats -> texel levels 1..15 (0 where v <= cut: transparent)."""
    v = np.clip(v, 0, 1)
    return np.where(v > cut, np.clip(np.round(v * 15), 1, 15), 0).astype(np.uint8)


def radius(w, h=None):
    h = h or w
    y, x = np.mgrid[0:h, 0:w]
    return np.hypot((x - (w - 1) / 2) / (w / 2), (y - (h - 1) / 2) / (h / 2))


# ---- the sprites

def glow(d):
    r = radius(d)
    return levels(np.clip(1 - r, 0, 1) ** 2.2 * 0.75 + np.clip(1 - r * 3.2, 0, 1) ** 1.2)


def dot(d):
    r = radius(d)
    return levels(np.clip(1 - r, 0, 1) ** 1.3)


def star(d):
    y, x = np.mgrid[0:d, 0:d]
    c = (d - 1) / 2
    dx, dy = np.abs(x - c) / (d / 2), np.abs(y - c) / (d / 2)
    arms = np.clip(1 - dx * 9 - dy, 0, 1) + np.clip(1 - dy * 9 - dx, 0, 1)
    core = np.clip(1 - np.hypot(dx, dy) * 2.8, 0, 1)
    return levels(arms + core)


def flare(w, h):
    """A white-hot core, a long thin horizontal streak and a short vertical spike."""
    y, x = np.mgrid[0:h, 0:w]
    dx = np.abs(x - (w - 1) / 2) / (w / 2)
    dy = np.abs(y - (h - 1) / 2) / (h / 2)
    streak = np.exp(-(dy * h / 2 / 0.9) ** 2) * np.clip(1 - dx, 0, 1) ** 1.4
    spike = np.exp(-(dx * w / 2 / 0.9) ** 2) * np.clip(1 - dy, 0, 1) ** 1.6 * 0.9
    r = np.hypot(dx * w / h, dy)
    core = np.clip(1 - r * 1.6, 0, 1) ** 1.5 + np.clip(1 - r, 0, 1) ** 3 * 0.4
    return levels(streak + spike + core)


def burst(d, seed=4):
    """The hit's starburst: a dozen sharp rays of uneven length round a hot core (the 1990s
    fighting-game hit spark)."""
    rng = np.random.default_rng(seed)
    y, x = np.mgrid[0:d, 0:d]
    c = (d - 1) / 2
    dx, dy = (x - c) / (d / 2), (y - c) / (d / 2)
    r = np.hypot(dx, dy)
    a = np.arctan2(dy, dx)
    v = np.zeros((d, d))
    n = 12
    for k in range(n):
        ang = 2 * math.pi * k / n + rng.uniform(-0.15, 0.15)
        ln = rng.uniform(0.55, 1.0) if k % 2 else rng.uniform(0.85, 1.0)
        da = np.abs((a - ang + math.pi) % (2 * math.pi) - math.pi)
        width = 0.34 * (1 - np.clip(r / ln, 0, 1)) ** 0.8
        v = np.maximum(v, np.clip(1 - da / np.maximum(width, 1e-3), 0, 1) * (r < ln))
    core = np.clip(1 - r * 2.6, 0, 1) ** 0.8
    return levels(np.maximum(v * 0.95, core * 1.2))


def ring(d):
    r = radius(d)
    edge = np.clip(1 - np.abs(r - 0.88) * 14, 0, 1)
    inner = np.clip(r / 0.88, 0, 1) ** 5 * (r < 0.88) * 0.3
    return levels(edge + inner)


def hexagon(d):
    """The shield: a pointy-topped hexagon's rim, its honeycomb faint inside, a bright centre."""
    S = d * SS
    img = Image.new('L', (S, S), 0)
    dr = ImageDraw.Draw(img)
    c = (S - 1) / 2

    def hexpts(cx, cy, R):
        return [(cx + R * math.sin(math.radians(60 * k)), cy - R * math.cos(math.radians(60 * k))) for k in range(6)]

    # the honeycomb: small cells, faint
    R = S * 0.13
    for j in range(-4, 5):
        for i in range(-4, 5):
            cx = c + i * R * math.sqrt(3) + (j % 2) * R * math.sqrt(3) / 2
            cy = c + j * R * 1.5
            dr.polygon(hexpts(cx, cy, R * 0.92), outline=70)
    mask = Image.new('L', (S, S), 0)
    ImageDraw.Draw(mask).polygon(hexpts(c, c, S * 0.47), fill=255)
    img = Image.composite(img, Image.new('L', (S, S), 0), mask)
    dr = ImageDraw.Draw(img)
    pts = hexpts(c, c, S * 0.46)
    dr.line(pts + [pts[0]], fill=255, width=int(SS * 1.6))
    a = np.asarray(img.resize((d, d), Image.BOX)).astype(np.float64) / 255
    a = np.maximum(a, np.clip(1 - radius(d) * 2.2, 0, 1) ** 1.5 * 0.8)
    inside = np.asarray(mask.resize((d, d), Image.BOX)).astype(np.float64) / 255
    return levels(np.maximum(a * 1.3, inside * 0.12))


def puff(d, seed, hd=None):
    """A smoke puff: overlapping soft blobs under a round falloff."""
    hd = hd or d
    rng = np.random.default_rng(seed)
    y, x = np.mgrid[0:hd, 0:d]
    v = np.zeros((hd, d))
    for _ in range(9):
        cx, cy = rng.uniform(0.3, 0.7) * d, rng.uniform(0.35, 0.65) * hd
        rr = rng.uniform(0.16, 0.3) * d
        v += np.exp(-(((x - cx) / rr) ** 2 + ((y - cy) / (rr * hd / d)) ** 2)) * rng.uniform(0.5, 1.0)
    v = v / v.max()
    fall = np.clip(1 - radius(d, hd), 0, 1) ** 0.8
    return levels((v * fall) ** 0.7 * 1.1, 0.06)


def speed(w, h):
    """A speed streak: thin, bright at its head (right), tapering to nothing behind."""
    y, x = np.mgrid[0:h, 0:w]
    u = x / (w - 1)
    dy = np.abs(y - (h - 1) / 2) / (h / 2)
    width = 0.25 + 0.75 * u
    v = np.clip(1 - dy / width, 0, 1) * u ** 1.3
    v = np.where(u > 0.93, v * (1 - (u - 0.93) / 0.07), v)
    return levels(v * 1.3)


def chevron(d):
    """A '>' chevron pointing right, its outer edge bright."""
    S = d * SS
    img = Image.new('L', (S, S), 0)
    dr = ImageDraw.Draw(img)
    pts = [(S * .12, S * .08), (S * .52, S * .08), (S * .92, S * .5), (S * .52, S * .92), (S * .12, S * .92), (S * .52, S * .5)]
    dr.polygon(pts, fill=150)
    dr.line([pts[1], pts[2], pts[3]], fill=255, width=int(SS * 1.5))
    return levels(np.asarray(img.resize((d, d), Image.BOX)).astype(np.float64) / 255 * 1.1, 0.08)


def bubble(d):
    r = radius(d)
    rim = np.clip(1 - np.abs(r - 0.8) * 7, 0, 1) * 0.8
    y, x = np.mgrid[0:d, 0:d]
    hl = np.clip(1 - np.hypot(x - d * 0.34, y - d * 0.32) / (d * 0.14), 0, 1)
    return levels(rim + hl + (r < 0.8) * 0.08)


def bolt(w, h, seed):
    """An electric arc: a jagged line from left to right with a glow."""
    rng = np.random.default_rng(seed)
    pts = [(0.0, 0.5), (1.0, 0.5)]
    for depth in range(5):
        out = [pts[0]]
        amp = 0.42 / (1.6 ** depth)
        for a, b in zip(pts, pts[1:]):
            m = ((a[0] + b[0]) / 2, (a[1] + b[1]) / 2 + rng.uniform(-amp, amp))
            out += [m, b]
        pts = out
    S = SS
    img = Image.new('L', (w * S, h * S), 0)
    dr = ImageDraw.Draw(img)
    xy = [(x * (w * S - 1), min(max(y, 0.1), 0.9) * (h * S - 1)) for x, y in pts]
    dr.line(xy, fill=110, width=int(S * 3.2))
    dr.line(xy, fill=255, width=int(S * 1.1))
    v = np.asarray(img.resize((w, h), Image.BOX)).astype(np.float64) / 255
    return levels(v * 1.4, 0.05)


SHARD = [(-0.62, -0.30), (0.10, -0.62), (0.66, -0.12), (0.20, 0.50), (-0.40, 0.34)]


def shard(d, angle):
    """A metal shard turned by angle: a lit facet, a darker facet and a bright rim on the lit
    side. Levels: rim 15, lit 11, dark 5."""
    S = d * SS
    c, a = (S - 1) / 2, math.radians(angle)
    pts = [(c + (x * math.cos(a) - y * math.sin(a)) * S * 0.48, c + (x * math.sin(a) + y * math.cos(a)) * S * 0.48) for x, y in SHARD]
    img = Image.new('L', (S, S), 0)
    mask = Image.new('L', (S, S), 0)
    dr = ImageDraw.Draw(img)
    ImageDraw.Draw(mask).polygon(pts, fill=255)
    centre = (sum(p[0] for p in pts) / 5, sum(p[1] for p in pts) / 5)
    # two facets split through the centre: the one facing up-left lit
    for k in range(5):
        p, q = pts[k], pts[(k + 1) % 5]
        mx, my = (p[0] + q[0]) / 2 - centre[0], (p[1] + q[1]) / 2 - centre[1]
        lit = (-mx - my) > 0
        dr.polygon([centre, p, q], fill=180 if lit else 75)
        if lit:
            dr.line([p, q], fill=255, width=int(SS * 1.2))
    v = np.asarray(img.resize((d, d), Image.BOX)).astype(np.float64)
    m = np.asarray(mask.resize((d, d), Image.BOX)).astype(np.float64) / 255
    with np.errstate(invalid='ignore', divide='ignore'):
        v = np.where(m > 0, v / np.maximum(m, 1e-6) / 255, 0)
    out = np.clip(np.round(v * 15), 1, 15).astype(np.uint8)
    return np.where(m > 0.45, out, 0).astype(np.uint8)


# ---- the sheet

class Sheet:
    """A 256 x 256 4-bit texture slot filled on shelves."""

    def __init__(self):
        self.img = np.zeros((256, 256), np.uint8)
        self.x = self.y = self.shelf = 0
        self.rects = []

    def place(self, name, idx, gap=1):
        h, w = idx.shape
        if self.x + w > 256:
            self.x, self.y, self.shelf = 0, self.y + self.shelf + gap, 0
        if self.y + h > 256:
            raise SystemExit('slot %d is full' % SLOT_FXP)
        u, v = self.x, self.y
        self.img[v:v + h, u:u + w] = idx
        self.x += w + gap
        self.shelf = max(self.shelf, h)
        self.rects.append((name, u, v, w, h))

    def used(self):
        return self.y + self.shelf

    def blob(self):
        t = self.img[:self.used()]
        return ((t[:, 0::2] & 15) | ((t[:, 1::2] & 15) << 4)).astype(np.uint8).tobytes()


def c15(v):
    return (v >> 3) | ((v >> 3) << 5) | ((v >> 3) << 10)


def main():
    preview = None
    if '--preview' in sys.argv:
        preview = sys.argv[sys.argv.index('--preview') + 1]
    sh = Sheet()
    sh.place('GLOW', glow(64))
    sh.place('RING', ring(64))
    sh.place('FLARE', flare(64, 32))
    sh.place('BURST', burst(48))
    sh.place('HEX', hexagon(32))
    sh.place('SMOKE0', puff(32, 7))
    sh.place('SMOKE1', puff(32, 11))
    sh.place('DUST', puff(32, 5, 16))
    sh.place('SPEED', speed(32, 8))
    sh.place('BOLT0', bolt(32, 16, 3))
    sh.place('BOLT1', bolt(32, 16, 8))
    sh.place('DOT', dot(16))
    sh.place('STAR', star(16))
    sh.place('CHEVRON', chevron(16))
    sh.place('BUBBLE', bubble(16))
    for k in range(8):
        sh.place('SHARD%d' % k, shard(16, k * 45))

    pal = [0] + [c15(17 * k) for k in range(1, 16)]
    tex = sh.blob()
    with open(os.path.join(ART, 'fx_particles.tex'), 'wb') as fh:
        fh.write(tex)
    with open(os.path.join(ART, 'fx_particles.pal'), 'wb') as fh:
        fh.write(struct.pack('<16H', *pal))

    rects = {n: (u, v, w, h) for n, u, v, w, h in sh.rects}
    akr = [HEADER,
           "// Mech Expo 2000's particle sprites (tools/gen_mechexpo_fx.py): white and grey sprites fx.akr",
           '// tints, in texture slot %d with their grey ramp in 4-bit palette %d.' % (SLOT_FXP, PAL_FXP),
           '',
           'embed FXP_TEX: u8 = "art/fx_particles.tex"',
           'embed FXP_PAL: u16 = "art/fx_particles.pal"',
           '',
           'const FXP_TEX_BYTES = %d' % len(tex),
           'const SLOT_FXP = %d' % SLOT_FXP,
           'const PAL_FXP = %d' % PAL_FXP,
           '',
           '// Copies the sprites and their palette into VRAM.',
           'fn fx_art_load() {',
           '    load_texture(SLOT_FXP, &FXP_TEX[0], FXP_TEX_BYTES)',
           '    load_palette(PAL_FXP * 16, &FXP_PAL[0], 16)',
           '}',
           '',
           '// sprite rectangles: u, v, w, h']
    for n, u, v, w, h in sh.rects:
        if not n.startswith('SHARD'):
            akr.append('const FXP_%s: [4]s32 = [%d, %d, %d, %d]' % (n, u, v, w, h))
    akr.append('// the shard turned by 0, 45, ... 315 degrees: frame k at FXP_SHARDS[k * 4]')
    sh_r = [rects['SHARD%d' % k] for k in range(8)]
    akr.append('const FXP_SHARDS: [32]s32 = [%s]' % ', '.join('%d, %d, %d, %d' % r for r in sh_r))
    with open(os.path.join(CART, 'fx_art.akr'), 'w') as fh:
        fh.write('\n'.join(akr) + '\n')

    if preview:
        os.makedirs(preview, exist_ok=True)
        g = [(40, 0, 60)] + [(17 * k,) * 3 for k in range(1, 16)]
        t = sh.img[:sh.used()]
        img = np.array([[g[i] for i in row] for row in t], np.uint8)
        Image.fromarray(img).resize((512, t.shape[0] * 2), Image.NEAREST).save(os.path.join(preview, 'fx_particles.png'))
    print('slot %d: %d rows, %d bytes' % (SLOT_FXP, sh.used(), len(tex)))


if __name__ == '__main__':
    main()
