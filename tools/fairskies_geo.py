def shapes():
    out = [(LAND, MAINLAND)]
    out += [(LAND, r) for r in ISLANDS]
    out += [(LAKE, r) for r in LAKES]
    out += [(BORDER, p) for p in BORDERS]
    out += [(STATE, p) for p in STATES]
    return out


if __name__ == '__main__':
    import sys
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        sys.exit('PIL needed for the preview')
    W, H = 1170, 500
    S, N, Wl, E = 24.5, 49.5, -125.0, -66.5

    def p(lat, lon):
        return ((lon - Wl) / (E - Wl) * W, (N - lat) / (N - S) * H)
    img = Image.new('RGB', (W, H), (20, 40, 92))
    d = ImageDraw.Draw(img)
    for kind, pts in shapes():
        xy = [p(*q) for q in pts]
        if kind == LAND:
            d.polygon(xy, fill=(120, 170, 110), outline=(230, 236, 250))
    for kind, pts in shapes():
        xy = [p(*q) for q in pts]
        if kind == LAKE:
            d.polygon(xy, fill=(20, 40, 92), outline=(230, 236, 250))
        elif kind == BORDER:
            d.line(xy, fill=(10, 10, 30), width=2)
        elif kind == STATE:
            d.line(xy, fill=(40, 50, 80), width=1)
    img.save(sys.argv[1] if len(sys.argv) > 1 else 'geo.png')
