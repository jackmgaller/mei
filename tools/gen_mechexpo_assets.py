#!/usr/bin/env python3
"""Generates the model pack of "Mech Expo 2000" (carts/mechexpo/README.md).

Writes, in carts/mechexpo/:
  art/          every mesh, texture slot and palette of the models, packed together by
                `mei_assets.py pack` (texture slots 0-7, 4-bit palettes from 0, 8-bit palettes
                from 14 down); art/stage_* and art/ui_* (D's) and art/fx_* (the
                effects', tools/gen_mechexpo_fx.py) are left alone
  assets.akr    the pack's embeds (every ASSET_*) and one loader, assets_load()

What is packed: for a model folder with a rig (models/NAME/NAME.rig.json), the part recipes the
rig names (each once: the Double-blade's two daggers are one mesh); for any other model folder
(the stage props), every *.asset.json in it. The mechs' assembled previews (NAME.asset.json,
NAME_rest.asset.json) are not packed: the game draws the parts.

A recipe the kit rejects (one still being written) is left out with a warning and the rest
packed. Prints the triangles of each asset, each mech's total against the README's budget, and
the VRAM, palettes and ROM used. Options: --dry-run (pack and print, write nothing); --check DIR
(a build directory with meic and mei-headless: compiles a probe cart that imports the written
assets.akr and draws each mech's parts at their rest-pose joints, and each prop, and saves the
frames as PNGs in DIR/mechexpo-assets/). Standard library only (Pillow for the recipes' images
and for --check's PNGs)."""
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CART = ROOT/'carts'/'mechexpo'
ART = CART/'art'
HEADER = '// Generated by tools/gen_mechexpo_assets.py - do not edit.'

PACK_NAME = 'mx_pack'
PACK_SLOTS = '0-7'          # README: B's pack uses texture slots 0-7, D 8-14
PALETTE = 0                 # 4-bit palettes from 0 up (D's are 240-254)
PALETTE8 = 14               # 8-bit palettes from 14 down
FOREIGN = ('stage_', 'ui_', 'fx_')  # art/stage_* and art/ui_* are D's, art/fx_* the effects'

MECH_LIMIT = 1800           # README: a mech about 1,600-1,800 triangles
PROP_LIMIT = {'wall': 300, 'banner': 260}

# The UAPC's test units (the arcade's final for a mech with no echo yet, mx-ladder): each of these
# bodies' parts again, the same geometry in the UAPC's plain grey (grey_recipe() below), packed
# after everything else as GREY_<PART> (ASSET_GREY_SHADOW_TORSO ...). assets.akr lists them in
# GREY_FROM / GREY_TO, which anim.akr turns into a grey mesh table. The Hero and the Double-blade
# Hero have each other as their finals and need none.
GREY_BODIES = ('shadow', 'beam', 'tank', 'twins', 'twin_a', 'twin_b')
GREY_DARK = (0x26, 0x29, 0x2f)      # a neutral colour of luminance 0 (gunmetal)
GREY_LIGHT = (0xe4, 0xe7, 0xeb)     # and of luminance 1 (white primer)
GREY_PAINT = ((0x86, 0x8d, 0x97), (0xc2, 0xc8, 0xcf))   # a maker's colour: the UAPC's paint, by luminance
GREY_GLOW = '#9fd6ff'               # the emissive glows: the UAPC's pale blue


def grey_colour(c):
    """A material colour (#rrggbb) in the test unit's grey: a maker's saturated colour becomes the
    UAPC's grey paint (lighter for a lighter colour), a neutral one keeps its lightness on a
    gunmetal-to-primer ramp, with a cool cast."""
    r, g, b = (int(c[i:i + 2], 16) / 255.0 for i in (1, 3, 5))
    lum = 0.299 * r + 0.587 * g + 0.114 * b
    mx, mn = max(r, g, b), min(r, g, b)
    sat = (mx - mn) / mx if mx > 0 else 0.0
    if sat > 0.25 and mx > 0.3:
        lo, hi = GREY_PAINT
        t = min(max((lum - 0.25) / 0.6, 0.0), 1.0)
    else:
        lo, hi = GREY_DARK, GREY_LIGHT
        t = lum ** 0.9
    return '#%02x%02x%02x' % tuple(round(lo[i] + (hi[i] - lo[i]) * t) for i in range(3))


def grey_recipe(path):
    """Part recipe `path` as the test unit's: named grey_NAME, every colour through grey_colour()
    (textures' colours too), the emissive glows GREY_GLOW."""
    r = json.loads(path.read_text())
    r['name'] = 'grey_' + r['name']
    for m in r.get('materials', {}).values():
        if m.get('class') == 'emissive':
            m['color'] = GREY_GLOW
            continue
        if 'color' in m:
            m['color'] = grey_colour(m['color'])
        tex = m.get('texture')
        if isinstance(tex, dict) and 'colors' in tex:
            tex['colors'] = [grey_colour(c) for c in tex['colors']]
    return r


def grey_recipes(rigs, out):
    """Writes the test units' part recipes into `out`; returns [(model, path)] to pack and
    [(asset, grey asset)] (ASSET_ names)."""
    found, pairs = [], []
    out.mkdir(parents=True, exist_ok=True)
    for model in GREY_BODIES:
        rig = rigs.get(model)
        if not rig:
            continue
        seen = []
        for part in rig['parts']:
            p = CART/'models'/model/part['recipe']
            if p in seen:
                continue
            seen.append(p)
            g = grey_recipe(p)
            q = out/f'{g["name"]}.asset.json'
            q.write_text(json.dumps(g, indent=1))
            found.append((model, q))
            pairs.append((part['asset'], 'ASSET_' + g['name'].upper()))
    return found, pairs


def rig_of(folder):
    p = folder/f'{folder.name}.rig.json'
    return json.loads(p.read_text()) if p.exists() else None


def recipes():
    """[(model, path)] of every recipe to pack, and {model: rig}."""
    out, rigs = [], {}
    for folder in sorted((CART/'models').glob('*')):
        if not folder.is_dir():
            continue
        rig = rig_of(folder)
        if rig:
            rigs[folder.name] = rig
            seen = []
            for part in rig['parts']:
                p = folder/part['recipe']
                if p not in seen:
                    seen.append(p)
            out += [(folder.name, p) for p in seen]
        else:
            out += [(folder.name, p) for p in sorted(folder.glob('*.asset.json'))]
    return out, rigs


def run_pack(found, work, skipped):
    """Packs `found` into `work`; a recipe the kit rejects is dropped (with its error in
    `skipped`) and the rest packed again. Returns the manifest, or None with nothing left."""
    while found:
        cmd = [sys.executable, str(ROOT/'tools'/'mei_assets.py'), 'pack', *[str(p) for _, p in found],
               '-o', str(work), '--name', PACK_NAME, '--slots', PACK_SLOTS,
               '--palette', str(PALETTE), '--palette8', str(PALETTE8)]
        run = subprocess.run(cmd, capture_output=True, text=True)
        try:
            result = json.loads(run.stdout)
        except json.JSONDecodeError:
            sys.exit(f'mei_assets.py pack failed:\n{run.stdout}\n{run.stderr}')
        if result.get('ok'):
            return json.loads((work/f'{PACK_NAME}.pack.json').read_text())
        errors = result.get('errors', [])
        bad = next((int(m.group(1)) for e in errors
                    for m in [re.match(r'/assets/(\d+)', e.get('path', ''))] if m), None)
        if bad is None:
            sys.exit('mei_assets.py pack failed:\n'+json.dumps(result, indent=2))
        _, path = found.pop(bad)
        name = path.relative_to(CART) if path.is_relative_to(CART) else path.name
        skipped.append(f'{name}: {errors[0].get("message", "")[:240]}')
    return None


def owned_art():
    """The files in art/ this generator wrote (everything but stage_*, ui_* and fx_*)."""
    if not ART.exists():
        return []
    return [p for p in ART.iterdir() if p.is_file() and not p.name.startswith(FOREIGN)]


def pose_matrices(rig, pose=None, at=(0.0, 0.0, 0.0), yaw=0.0):
    """{part id: (rotation 3x3, translation)} of every part (parents first), in a pose of the
    rig's `poses` (None: the rest pose), the root at `at` and turned `yaw` degrees about Y (the
    kit's sense: 90 turns the -Z front to -X)."""
    import math

    def rot(e):
        out = [[1, 0, 0], [0, 1, 0], [0, 0, 1]]
        for axis, a in zip('xyz', e):
            c, s = math.cos(math.radians(a)), math.sin(math.radians(a))
            r = {'x': [[1, 0, 0], [0, c, -s], [0, s, c]], 'y': [[c, 0, s], [0, 1, 0], [-s, 0, c]],
                 'z': [[c, -s, 0], [s, c, 0], [0, 0, 1]]}[axis]
            out = [[sum(r[i][k]*out[k][j] for k in range(3)) for j in range(3)] for i in range(3)]
        return out

    def mul(a, b):
        return [[sum(a[i][k]*b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]
    angles = rig['poses'][pose]['rotate'] if pose else {}
    drop = rig['poses'][pose]['drop'] if pose else 0.0
    root_r = rot([0, yaw, 0])
    mats = {}
    for p in rig['parts']:
        r = rot(p['rotate']) if 'rotate' in p else rot(angles.get(p['id'], [0, 0, 0]))
        if p['parent'] is None:
            off = [p['offset'][0], p['offset'][1]-drop, p['offset'][2]]
            mats[p['id']] = (mul(root_r, r),
                             [at[i]+sum(root_r[i][k]*off[k] for k in range(3)) for i in range(3)])
        else:
            pr, pt = mats[p['parent']]
            t = [pt[i]+sum(pr[i][k]*p['offset'][k] for k in range(3)) for i in range(3)]
            mats[p['id']] = (mul(pr, r), t)
    return mats


def draw_mech(rig, names, pose=None, at=(0.0, 0.0, 0.0), yaw=0.0):
    """Akari lines drawing a mech's parts with mesh_xf."""
    lines = []
    mats = pose_matrices(rig, pose, at, yaw)
    for p in rig['parts']:
        if p['asset'][len('ASSET_'):].lower() not in names:
            continue
        r, t = mats[p['id']]
        rows = ', '.join(f'vec4({r[i][0]:.5f}, {r[i][1]:.5f}, {r[i][2]:.5f}, {t[i]:.4f})'
                         for i in range(3))
        lines.append(f'        mesh_xf({p["asset"]}, xf({rows}))')
    return lines


def probe(build, manifest, rigs):
    """Compiles and runs a cart that imports the written assets.akr (meic -I carts/mechexpo) and
    draws: each mech from its parts (mesh_xf) at the rig's rest joints and in its guard pose,
    each prop alone, and the stage as the game's side camera sees it (the walls at x = +-36, the
    banner towers behind, the two mechs in their guard poses at x = +-9, then cornered at the
    right wall, then the whole arena); saves each view as a PNG (2x), and the GPU's statistics
    (gpu.csv beside the frames)."""
    meic, run = Path(build)/'meic', Path(build)/'mei-headless'
    out = Path(build)/'mechexpo-assets'
    work = out/'probe'
    work.mkdir(parents=True, exist_ok=True)
    for p in list(out.glob('*.png'))+list(work.glob('f_*.ppm')):
        p.unlink()
    names = {a['name'] for a in manifest['assets']}
    side = 'camera_look(vec3(-22.0, 6.0, 0.0), 1.5708, 0.0)'
    views = []          # (label, camera, [akari lines that draw])
    for mech, rig in rigs.items():
        views.append((f'{mech}_rest', side, draw_mech(rig, names)))
        if 'guard' in rig.get('poses', {}):
            views.append((f'{mech}_guard', side, draw_mech(rig, names, 'guard')))
    for mech in GREY_BODIES:          # the test units, in their guard poses
        rig = rigs.get(mech)
        if rig and 'guard' in rig.get('poses', {}):
            grey = dict(rig, parts=[dict(p, asset='ASSET_GREY_' + p['asset'][6:]) for p in rig['parts']])
            views.append((f'grey_{mech}_guard', side, draw_mech(grey, names, 'guard')))
    props = [a['name'] for a in manifest['assets']
             if not any(a['name'].startswith(m+'_') or a['name'].startswith('grey_'+m+'_') for m in rigs)]
    for n in props:
        views.append((n, 'camera_look(vec3(-24.0, 9.0, -30.0), 0.65, -0.05)',
                      [f'        mesh_at(ASSET_{n.upper()}, vec3(0.0, 0.0, 0.0), 0.0)']))
    stage = []
    for n, at in (('hangar_wall_l', '-36.0, 0.0, 0.0'), ('hangar_wall_r', '36.0, 0.0, 0.0'),
                  ('expo_banner', '-19.0, 0.0, 12.0'), ('expo_banner', '21.0, 0.0, 15.0')):
        if n in names:
            stage.append(f'        mesh_at(ASSET_{n.upper()}, vec3({at}), 0.0)')
    mechs = list(rigs.items())
    if len(mechs) >= 2 and stage:
        (m1, r1), (m2, r2) = mechs[1], mechs[0]          # hero on the left, the echo right
        pose = 'guard'
        views.append(('stage_start', 'camera_look(vec3(0.0, 6.5, -34.0), 0.0, 0.0)',
                      stage + draw_mech(r1, names, pose, (-9.0, 0, 0), -90)
                      + draw_mech(r2, names, pose, (9.0, 0, 0), 90)))
        views.append(('stage_cornered', 'camera_look(vec3(26.0, 6.5, -32.0), 0.0, 0.0)',
                      stage + draw_mech(r1, names, pose, (22.0, 0, 0), -90)
                      + draw_mech(r2, names, pose, (32.5, 0, 0), 90)))
        views.append(('stage_arena', 'camera_look(vec3(0.0, 9.0, -58.0), 0.0, 0.0)',
                      stage + draw_mech(r1, names, pose, (-30.0, 0, 0), -90)
                      + draw_mech(r2, names, pose, (30.0, 0, 0), 90)))
    lines = ['cart "Mech Expo assets probe"', 'import "assets.akr"', 'import "depth.akr"', '',
             'var t: s32 = 0', '', 'fn init() { assets_load() }', '',
             'fn xf(a: vec4, b: vec4, c: vec4) -> mat4 {', '    var m: mat4', '    m[0] = a',
             '    m[1] = b', '    m[2] = c', '    m[3] = vec4(0.0, 0.0, 0.0, 1.0)', '    return m', '}', '',
             'fn update() { t += 1 }', '',
             'fn draw() {', '    let view = t / 4', '    cls(rgb(120, 134, 156))',
             '    render_depth(true)', '    render_perspective(true)', '    camera_clip(0.5, 300.0)']
    for k, (_, cam, draw) in enumerate(views):
        lines += [f'    if view == {k} {{', f'        {cam}'] + draw + ['    }']
    lines += ['}', '']
    (work/'probe.akr').write_text('\n'.join(lines))
    r = subprocess.run([str(meic), str(work/'probe.akr'), '-o', str(work/'probe.mei'), '-I', str(CART)],
                       capture_output=True, text=True)
    if r.returncode:
        sys.exit(f'the probe cart does not compile:\n{r.stdout}{r.stderr}')
    r = subprocess.run([str(run), str(work/'probe.mei'), '--frames', str(4*len(views)+1), '--quiet',
                        '--dump-every', '4', str(work/'f'), '--dump-from', '2',
                        '--gpu-stats', str(work/'gpu.csv')], capture_output=True, text=True)
    if r.returncode:
        sys.exit(f'the probe cart failed:\n{r.stdout}{r.stderr}')
    shots = sorted(work.glob('f_*.ppm'))
    try:
        from PIL import Image
    except ImportError:
        print(f'probe: compiled and ran; {len(shots)} frames as PPM in {work}')
        return
    for k, (n, _, _) in enumerate(views):
        if k < len(shots):
            im = Image.open(shots[k])
            im.resize((im.width*2, im.height*2), Image.NEAREST).save(out/f'{k:02}_{n}.png')
    print(f'probe: compiled and ran; {min(len(shots), len(views))} views in {out}/')


def main():
    dry = '--dry-run' in sys.argv
    check = sys.argv[sys.argv.index('--check')+1] if '--check' in sys.argv else None
    found, rigs = recipes()
    skipped, warnings = [], []
    work = Path(tempfile.mkdtemp(prefix='mechexpo-pack-'))
    grey_dir = Path(tempfile.mkdtemp(prefix='mechexpo-grey-'))
    try:
        grey_found, grey_pairs = grey_recipes(rigs, grey_dir)
        found += grey_found
        manifest = run_pack(found, work, skipped) if found else None

        lines = [HEADER,
                 '// The pack of every model under models/ (mei_assets.py pack: texture slots 0-7,',
                 f'// 4-bit palettes from {PALETTE}, 8-bit from {PALETTE8} down): each mech\'s parts as its rig',
                 '// (models/NAME/NAME.rig.json) names them, and the stage props; assets_load() loads it',
                 '// once. Draw the meshes with the depth test on (render_depth(true),',
                 '// render_perspective(true)).', '']
        if manifest:
            for line in (work/f'{PACK_NAME}.akr').read_text().splitlines():
                lines.append(re.sub(r'^(embed [^=]*= ")([^"]+)"', r'\1art/\2"', line))
        else:
            lines.append('// No recipes yet.')
        if manifest:
            names = {'ASSET_' + a['name'].upper() for a in manifest['assets']}
            grey = [(a, g) for a, g in grey_pairs if a in names and g in names]
            lines += ['', '// The UAPC\'s test units (mx-ladder): each part of ' + ', '.join(GREY_BODIES) + ' and',
                      '// its grey copy (GREY_BODIES in the generator); anim.akr draws a fighter grey through these.',
                      f'const GREY_N = {len(grey)}',
                      f'const GREY_FROM: [{max(len(grey), 1)}]*Mesh = [',
                      *([f'    {a},' for a, _ in grey] or ['    null,']), ']',
                      f'const GREY_TO: [{max(len(grey), 1)}]*Mesh = [',
                      *([f'    {g},' for _, g in grey] or ['    null,']), ']']
        lines += ['', 'fn assets_load() {']
        if manifest:
            lines.append(f'    {PACK_NAME}_load()')
        lines += ['}', '']
        assets_akr = '\n'.join(lines)

        if manifest:
            by_name = {a['name']: a for a in manifest['assets']}
            print('triangles:')
            for a in manifest['assets']:
                ntex = len(a.get('textures', []))
                print(f'       {a["name"]:28} {a["triangles"]:5}, {a["vertices"]} vertices'
                      + (f', {ntex} textures' if ntex else ''))
            for mech, rig in rigs.items():
                total = sum(by_name[p['asset'][6:].lower()]['triangles'] for p in rig['parts']
                            if p['asset'][6:].lower() in by_name)
                flag = 'OVER   ' if total > MECH_LIMIT else '       '
                if total > MECH_LIMIT:
                    warnings.append(f'{mech}: {total} triangles drawn, over {MECH_LIMIT}')
                print(f'{flag}{mech+" (drawn, all parts)":28} {total:5}  ({MECH_LIMIT})')
            for a in manifest['assets']:
                kind = next((k for k in PROP_LIMIT if k in a['name']), None)
                if kind and not any(a['name'].startswith(m+'_') or a['name'].startswith('grey_'+m+'_') for m in rigs) \
                        and a['triangles'] > PROP_LIMIT[kind]:
                    warnings.append(f'{a["name"]}: {a["triangles"]} triangles, over {PROP_LIMIT[kind]}')
            tex = manifest.get('textures') or {}
            vram = sum(t['vram_bytes'] for a in manifest['assets'] for t in a.get('textures', []))
            slots = tex.get('slots', [])
            slot_bytes = sum((work/f'{PACK_NAME}.slot{s}.tex').stat().st_size for s in slots)
            print(f'VRAM: {vram} bytes of texels (tiles before de-duplication), slots {slots}, '
                  f'{slot_bytes} bytes loaded')
            pals = set()
            for first, count in re.findall(r'load_palette\((\d+), [^,]+, (\d+)\)',
                                           (work/f'{PACK_NAME}.akr').read_text()):
                pals |= set(range(int(first)//16, (int(first)+int(count)-1)//16+1))
            print('4-bit palettes (palette-backed, emissive and textured materials): '
                  + (f'{min(pals)}-{max(pals)} ({len(pals)})' if pals else 'none'))
            if pals and max(pals) >= 240:
                warnings.append(f'palettes up to {max(pals)}: 240-254 are D\'s')
            rom = sum(p.stat().st_size for p in work.iterdir() if p.suffix not in ('.akr', '.json'))
            print(f'ROM: {rom} bytes in art/')
        else:
            print('no recipes yet: assets.akr defines assets_load() only')
        for s in skipped:
            print('SKIPPED', s)
        for w in warnings:
            print('WARNING', w)
        if dry:
            return

        for p in owned_art():
            p.unlink()
        ART.mkdir(exist_ok=True)
        if manifest:
            for p in sorted(work.iterdir()):
                if p.suffix not in ('.akr',):
                    shutil.copy2(p, ART/p.name)
        (CART/'assets.akr').write_text(assets_akr)
        print('wrote carts/mechexpo/art/ (all but stage_*, ui_* and fx_*), carts/mechexpo/assets.akr')
        if check:
            probe(check, manifest, rigs)
    finally:
        shutil.rmtree(work, ignore_errors=True)
        shutil.rmtree(grey_dir, ignore_errors=True)


if __name__ == '__main__':
    main()
