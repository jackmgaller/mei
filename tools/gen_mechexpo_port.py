# ---- colour: sodium light

LAMP = (1.0, 0.74, 0.46)        # high-pressure sodium, as a multiplier


def sodium(c, lit=1.0, grey=0.22):
    """A colour (#rrggbb or rgb) as it shows under the port's floodlights: multiplied by the lamp,
    a little greyed (sodium light renders colour poorly) and scaled by `lit`. Returns rgb."""
    if isinstance(c, str):
        c = hexc(c)
    r, g, b = (v * k for v, k in zip(c, LAMP))
    m = (r + g + b) / 3
    out = [(v + (m - v) * grey) * lit for v in (r, g, b)]
    return tuple(int(max(0, min(255, round(v)))) for v in out)


def hexs(c):
    return '#%02x%02x%02x' % tuple(c)


def shex(c, lit=1.0, grey=0.22):
    return hexs(sodium(c, lit, grey))


