def build_sky(preview):
    cv, pals = draw_sky()
    rgb, alpha = cv.arrays()
    t = S.Tiler(pals, limit=1024)
    m = t.cut(rgb, alpha, 64, 32)
    if preview:
        cv.img.save(os.path.join(preview, 'stage_port_sky.png'))
        S.render_map(t, m, 8, os.path.join(preview, 'stage_port_sky_tiles.png'))
    return t, m


