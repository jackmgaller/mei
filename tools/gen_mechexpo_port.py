# The floodlights' pools on the asphalt: (x, z, radius, strength): the cranes' portal lights over
# the rail behind the fight, the yard's mast by the wall, the quay corner's mast.
POOLS = [(-2.0, 22.0, 22.0, 0.75), (42.0, 22.0, 22.0, 0.7), (36.0, -6.0, 16.0, 0.45),
         (-22.0, 30.0, 18.0, 0.35), (14.0, -18.0, 20.0, 0.3)]

BAYER = np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]) / 16.0


def light(x, z):
    """The asphalt's brightness 0..1 at world (x, z): the pools over a dim base, darker toward
    the open edge's black water."""
    v = 0.28
    for px, pz, r, s in POOLS:
        d2 = ((x - px) ** 2 + (z - pz) ** 2) / (r * r)
        v += s * math.exp(-1.6 * d2)
    v *= 0.55 + 0.45 * min(1.0, max(0.0, (x + PORT_HALF) / 14.0))
    return min(v, 1.0)


def draw_deck():
    sz = DECK_N * 8
    cv = S.Canvas(sz, sz)
    A = ASPHALT
    acc = DECK_ACC

    def X(x):
        return int(round(DECK_C + x * DECK_S))

    def Z(z):
        return int(round(DECK_C + z * DECK_S))

    x0, x1 = X(-PORT_HALF), sz
    z0, z1 = 0, Z(DECK_FAR)
    # the asphalt: per 8 x 8 tile a light level, per texel a 16 x 16 grain and a Bayer dither
    # between two neighbouring tones of the ramp (so tiles repeat: about 40 levels x 4 phases)
    rng = np.random.default_rng(2000)
    grain = rng.random((8, 8)) * 0.9 - 0.45
    grain[rng.random((8, 8)) < 0.06] -= 0.9                   # pits
    # patched rectangles (newer asphalt, darker) and worn ones (lighter), on the tile grid
    patches = [(-24, -20, -12, -2, -0.9), (4, -40, 22, -26, -0.7), (16, 4, 30, 12, -0.6),
               (-12, 10, 2, 19, 0.6), (-28, -6, -20, 8, 0.5)]
    img = np.zeros((sz, sz, 3), np.uint8)
    alpha = np.zeros((sz, sz), bool)
    for ty in range(z0 // 8, z1 // 8):
        for tx in range(x0 // 8, x1 // 8):
            wx = (tx * 8 + 4 - DECK_C) / DECK_S
            wz = (ty * 8 + 4 - DECK_C) / DECK_S
            lv = round(light(wx, wz) * 8 * 4) / 4                # quarter steps
            for px, pz, qx, qz, d in patches:
                if px <= wx < qx and pz <= wz < qz:
                    lv += d
            g = grain
            v = lv + g + BAYER[np.arange(8)[:, None] % 4, np.arange(8)[None, :] % 4] - 0.5
            idx = np.clip(np.round(v).astype(int), 0, 9)
            img[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8] = np.array(A)[idx]
            alpha[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8] = True
    cv.img = Image.fromarray(np.dstack([img, alpha.astype(np.uint8) * 255]), 'RGBA')
    cv.d = ImageDraw.Draw(cv.img)
    cv.d.fontmode = '1'

    def lit_pick(x, z, lit_c, dim_c):
        return lit_c if light(x, z) > 0.45 else dim_c

    # the slabs' seams (6 m) and a twist-lock socket at each crossing
    for sx in range(-24, 64, 6):
        for z in range(z0, z1 - 6):
            if z % 24 < 21:
                cv.rect(X(sx), z, X(sx) + 1, z + 1, A[1])
    for sz_ in range(-60, 20, 6):
        for x in range(x0 + 10, x1):
            if x % 24 < 21:
                cv.rect(x, Z(sz_), x + 1, Z(sz_) + 1, A[1])
    for sx in range(-24, 64, 6):
        for sz_ in range(-60, 20, 6):
            px, pz = X(sx), Z(sz_)
            st = acc['rail']
            cv.rect(px - 1, pz - 1, px + 2, pz + 2, lit_pick(sx, sz_, st[1], A[5]))
            cv.rect(px, pz, px + 1, pz + 1, st[2])
    # oil stains: dark blobs
    for k in range(10):
        ox = float(rng.uniform(-26, 60))
        oz = float(rng.uniform(-40, 16))
        r = float(rng.uniform(0.6, 1.6))
        cv.ellipse(X(ox - r), Z(oz - r * 0.7), X(ox + r), Z(oz + r * 0.7), A[1])
    # yellow lane lines along x: a double line at z = -7, a single one at z = 7 (worn: gaps)
    pa = acc['paint']
    for z, w in ((-7.25, 1), (-6.75, 1), (7.0, 2)):
        for x in range(x0 + 12, x1):
            wx = (x - DECK_C) / DECK_S
            if x % 40 < 33:
                cv.rect(x, Z(z), x + 1, Z(z) + w, lit_pick(wx, z, pa[0], pa[1]))
    # a dashed white line along x at z = -16, arrows toward the open edge
    for x in range(x0 + 12, x1, 32):
        wx = (x - DECK_C) / DECK_S
        cv.rect(x, Z(-16), x + 16, Z(-16) + 1, lit_pick(wx, -16, pa[2], pa[3]))
    for ax in (-14.0, 20.0, 50.0):
        c = lit_pick(ax, -12, pa[2], pa[3])
        cv.poly([(X(ax - 1.5), Z(-12)), (X(ax), Z(-12.9)), (X(ax), Z(-12.4)),
                 (X(ax + 1.5), Z(-12.4)), (X(ax + 1.5), Z(-11.6)), (X(ax), Z(-11.6)),
                 (X(ax), Z(-11.1))], c)
    # the berth's lettering behind the fight, read from the camera (rows run away: flip)
    mk = acc['mark']

    def deck_text(x, z, s, f, col):
        tmp = Image.new('RGBA', (360, 48), (0, 0, 0, 0))
        td = ImageDraw.Draw(tmp)
        td.fontmode = '1'
        td.text((180, 24), s, font=f, fill=col + (255,), anchor='mm')
        tmp = tmp.transpose(Image.FLIP_TOP_BOTTOM)
        cv.img.alpha_composite(tmp, (X(x) - 180, Z(z) - 24))
    deck_text(-3, 13.0, 'D-5', S.font(S.F_BLACK, 40), mk[1])
    deck_text(16, 13.6, 'HONMOKU PIER', S.font(S.F_COND, 14), mk[3])
    deck_text(16, 11.8, 'BERTH D-5  //  MAX 50 T/m²', S.font(S.F_COND, 10), mk[3])
    # the open edge: the quay's coping, 1.2 m of pale concrete, its yellow edge line inboard
    ed = acc['edge']
    cx1 = X(-PORT_HALF + 1.2)
    cv.rect(x0, z0, cx1, z1, ed[1])
    for z in range(z0, z1, 8):
        cv.rect(x0, z, cx1, z + 1, ed[3])
    cv.rect(x0, z0, x0 + 2, z1, ed[0])
    cv.rect(cx1 - 2, z0, cx1, z1, ed[2])
    # the landside crane rail at the far edge: a steel plate, the groove, the rail's head
    rl = acc['rail']
    rz = Z(DECK_FAR)
    cv.rect(x0, rz - 6, x1, rz, rl[1])
    cv.rect(x0, rz - 4, x1, rz - 1, rl[2])
    cv.rect(x0, rz - 3, x1, rz - 2, rl[0])
    for x in range(x0, x1, 12):
        cv.rect(x, rz - 6, x + 1, rz - 4, rl[2])
    pals = [[None] + ASPHALT + DECK_ACC[k] for k in DECK_ORDER]
    return cv, pals


def build_deck(preview):
    cv, pals = draw_deck()
    rgb, alpha = cv.arrays()
    t = S.Tiler(pals, limit=1024)
    m = t.cut(rgb, alpha, DECK_N, DECK_N)
    if preview:
        c = DECK_C
        cv.img.crop((c - 34 * DECK_S, c - 30 * DECK_S, c + 64 * DECK_S, c + 22 * DECK_S)).transpose(
            Image.FLIP_TOP_BOTTOM).save(os.path.join(preview, 'stage_port_deck.png'))
    return t, m


def bgr(s):
    r, g, b = hexc(s)
    return '0x%02X%02X%02X' % (b, g, r)


