def cell_rand(x, y, salt):
    """A repeatable 0..1 for (x, y)."""
    v = (x * 73856093) ^ (y * 19349663) ^ (salt * 83492791)
    v &= 0xFFFFFFFF
    v = ((v ^ (v >> 13)) * 1274126177) & 0xFFFFFFFF
    return ((v ^ (v >> 16)) & 0xFFFF) / 65536.0


