def pack(folder, script, names, pack_name, slots, palette, akr, what):
    """Runs props/FOLDER/SCRIPT (it writes the recipes), then `mei_assets.py pack` on them
    alone (texture slots `slots`, 4-bit palettes from `palette`), so the models' pack is not
    touched. Writes art/PACK_NAME.* and the meshes, and AKR. Returns the manifest."""
    props = os.path.join(CART, 'props', folder)
    subprocess.run([sys.executable, os.path.join(props, script)], check=True)
    recipes = [os.path.join(props, n + '.asset.json') for n in names]
    work = tempfile.mkdtemp(prefix='mechexpo-port-')
    try:
        run = subprocess.run([sys.executable, os.path.join(S.ROOT, 'tools', 'mei_assets.py'), 'pack',
                              *recipes, '-o', work, '--name', pack_name, '--slots', str(slots),
                              '--palette', str(palette), '--palette8', str(PALETTE8)],
                             capture_output=True, text=True)
        try:
            result = json.loads(run.stdout)
        except ValueError:
            sys.exit('mei_assets.py pack failed:\n' + run.stdout + run.stderr)
        if not result.get('ok'):
            sys.exit('mei_assets.py pack failed:\n' + json.dumps(result, indent=2))
        meshes = ['stage_' + n for n in names]
        for p in os.listdir(ART):
            if p.startswith(pack_name + '.') or any(p.startswith(m + '.') for m in meshes):
                os.unlink(os.path.join(ART, p))
        for p in sorted(os.listdir(work)):
            if not p.endswith('.akr'):
                shutil.copy2(os.path.join(work, p), os.path.join(ART, p))
        lines = [HEADER,
                 '// %s, packed on their own by' % what,
                 '// tools/gen_mechexpo_port.py: texture slots %s, 4-bit palettes from %d.' % (
                     slots, palette), '']
        for line in open(os.path.join(work, pack_name + '.akr')).read().splitlines():
            lines.append(re.sub(r'^(embed [^=]*= ")([^"]+)"', r'\1art/\2"', line))
        with open(os.path.join(CART, akr), 'w') as fh:
            fh.write('\n'.join(lines) + '\n')
        man = json.load(open(os.path.join(work, pack_name + '.pack.json')))
        for a in man['assets']:
            print('%s: %d triangles' % (a['name'], a['triangles']))
        return man
    finally:
        shutil.rmtree(work, ignore_errors=True)


def last_palette(man, first):
    """The highest 4-bit palette a pack's manifest names (or first - 1)."""
    hi = first - 1
    for m in re.finditer(r'"palette": (\d+)', json.dumps(man)):
        hi = max(hi, int(m.group(1)))
    for a in man['assets']:
        for p in a.get('palettes', []) if isinstance(a.get('palettes'), list) else []:
            if isinstance(p, int):
                hi = max(hi, p)
    return hi


