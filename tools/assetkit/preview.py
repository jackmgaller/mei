import math
from pathlib import Path
import re

from kitcore import native, depth as DEPTH
from kitcore.native import png_bytes  # noqa: F401 (re-exported for visibility.py)
import meshlib
from .geometry import AssetError


VIEWS = [('isometric',-0.65,-0.35),('front',0,0),('right',-math.pi/2,0),
         ('back',math.pi,0),('top',0,-math.pi/2),('rear_quarter',2.5,-0.35)]


def fitting(bounds, world=False):
    """(center, scale, radius) of the drawn mesh: centred, and fitted to about 2 units unless world
    (the mesh at its own size, the Asset Checker's world scale); radius is the drawn bounding
    sphere's."""
    lo,hi = bounds['min'],bounds['max']
    center = [(a+b)/2 for a,b in zip(lo,hi)]
    scale = 1.0 if world else min(8192,2/max(b-a for a,b in zip(lo,hi)))
    radius = math.sqrt(sum(((b-a)*scale/2)**2 for a,b in zip(lo,hi)))
    return center,scale,radius


def camera_numbers(bounds, yaw, pitch, distance_scale=1.0, world=False):
    """The camera of a view as the cart's literals: eye x, y, z (in the drawn mesh's space), yaw
    and pitch, each formatted as source() writes it."""
    _,_,radius = fitting(bounds,world)
    distance = max(1, radius*2.6)*distance_scale
    eye = (-math.sin(yaw)*math.cos(pitch)*distance,-math.sin(pitch)*distance,-math.cos(yaw)*math.cos(pitch)*distance)
    return [f'{n:.7f}' for n in (*eye,yaw,pitch)]


TOOLS_HINT = ('Build it with make (make B=DIR for a build directory of your own), or point the kit at your build '
              'directory with --build-dir DIR (or B, MEIC and RUN in the environment, or --compiler and --runner).')
FAILED_BANNER ='    text(8, 20, "VERIFICATION FAILED", rgb(255, 64, 64))\n'


def source(name, bounds, yaw=-0.65, pitch=-0.35, view='isometric', distance_scale=1.0, load=False, world=False,
           depth=False, perspective=None, failing=False, look=None):
    center,scale,radius = fitting(bounds,world)
    distance = max(1, radius*2.6)*distance_scale
    f = lambda n: f'{n:.7f}'
    camera = camera_numbers(bounds,yaw,pitch,distance_scale,world)
    # Palette-backed assets load their swatch and default palette once.
    init = f'fn init() {{ asset_{name}_load() }}\n\n' if load else ''
    # An asset drawn with the depth buffer (a textured asset's policy depth, or preview --depth)
    # previews so; perspective alone (preview --perspective) only corrects its textures. A ground
    # needs the depth buffer (look_passes()).
    ground = bool(look and look['ground'])
    depth = depth or ground
    perspective = depth if perspective is None else perspective or depth
    imports = f'import "{name}.akr"\n'+DEPTH.cart_import(depth,perspective)
    if ground:
        imports += 'embed PREVIEW_GROUND: Mesh = "preview_ground.bin"\n' \
                   'embed PREVIEW_GROUND_TINT: Mesh = "preview_ground_tint.bin"\n'
    modes = DEPTH.cart_lines(depth,perspective)
    far = distance+radius+1
    if ground:
        far = max(far,distance+ground_half(bounds)*scale*1.5)
    clear,before,after,colours = look_passes(look,'mesh_xf(PREVIEW_GROUND, model)','mesh_xf(PREVIEW_GROUND_TINT, model)')
    return f'''// Generated by Mei Asset Kit. This displays the original exported mesh.
cart "Asset preview"
{imports}
{init}fn draw() {{
{clear}{modes}    camera_clip(0.1, {f(far)})
    camera_look(vec3({', '.join(camera[:3])}), {camera[3]}, {camera[4]})
    var model = mat4_scale(vec3({f(scale)}, {f(scale)}, {f(scale)}))
    model[0].w = {f(-center[0]*scale)}
    model[1].w = {f(-center[1]*scale)}
    model[2].w = {f(-center[2]*scale)}
{before}    mesh_xf(ASSET_{name.upper()}, model)
{after}    text(8, 8, "{name.upper()}", {colours[0]})
    text(8, 224, "{view.upper()}", {colours[1]})
{FAILED_BANNER if failing else ''}}}
'''


# ---- the look: the background and the ground (preview --background, --ground, --look)

LOOK_FILE = 'asset-preview.json'    # a look for the recipes in its folder and below (find_look())
DARK = (24, 28, 36)                 # the background without a look
GROUND_TILES = 16                   # at most this many ground tiles along a side
GROUND_SHADE = 0.96                 # every other tile is the ground's colour times this
LIGHT = 140                         # a background brighter than this (luma, 0-255) gets dark HUD text


def colour(text, path):
    """'#rrggbb' -> (r, g, b)."""
    if not isinstance(text,str) or not re.fullmatch(r'#[0-9a-fA-F]{6}',text):
        raise AssetError(path,f'Colour {text!r}: give #rrggbb.')
    return tuple(int(text[k:k+2],16) for k in (1,3,5))


def hex_colour(c):
    return '#'+''.join(f'{n:02x}' for n in c)


def make_look(background=None, ground=None, path='/arguments', source=None):
    """A look: {'background': [top] or [top, bottom], 'ground': (r, g, b) or None, 'from': where
    it came from}. background: '#rrggbb', '#top,#bottom' or a list of one or two colours; ground:
    '#rrggbb', or None or 'none' for no ground. None when neither is given: the dark background
    and no ground, the views as they were before looks."""
    if isinstance(background,str): background = background.split(',')
    if ground == 'none': ground = None
    if not background and ground is None: return None
    if background is not None and (not isinstance(background,list) or not 1 <= len(background) <= 2):
        raise AssetError(path+'/background','A background is one colour (#rrggbb) or two, top and bottom (#top,#bottom).')
    sky = [colour(c.strip() if isinstance(c,str) else c,path+'/background') for c in background] if background else [DARK]
    return {'background':sky,'ground':colour(ground,path+'/ground') if ground is not None else None,
            **({'from':source} if source else {})}


def look_file(path):
    """A look file: {"background": "#rrggbb" or ["#top", "#bottom"], "ground": "#rrggbb"} (both optional)."""
    from kitcore import jsonio
    value = jsonio.load(str(path),AssetError)
    if not isinstance(value,dict) or set(value)-{'background','ground'}:
        raise AssetError('/look',f'{path}: a look file is {{"background": "#rrggbb" or ["#top", "#bottom"], "ground": "#rrggbb"}}.')
    return value


def find_look(recipe_path, stop=None):
    """The nearest LOOK_FILE in the recipe's folder or a folder above it (up to stop, the
    repository), or None (also for a recipe read from stdin)."""
    if not recipe_path or recipe_path == '-': return None
    folder = Path(recipe_path).resolve().parent
    stop = Path(stop).resolve() if stop else None
    for directory in (folder,*folder.parents):
        if (directory/LOOK_FILE).is_file(): return directory/LOOK_FILE
        if directory == stop: break
    return None


def look_report(look):
    """The look as report.json gives it."""
    return {'background':[hex_colour(c) for c in look['background']],
            'ground':hex_colour(look['ground']) if look['ground'] else None,**({'from':look['from']} if 'from' in look else {})}


def rgb_literal(c):
    return f'rgb({c[0]}, {c[1]}, {c[2]})'


def look_passes(look, ground, tint):
    """(clear, before the asset, after it, HUD colours) of a preview cart. Without a look: the dark
    background. With one: its background, one colour or a vertical gradient drawn first; and with a
    ground, three passes under the depth buffer: the ground (drawn and flushed), the depth buffer
    cleared, the asset (all of it, so what is below y = 0 too), then the ground again, half
    transparent, which tests against the asset: where a part lies below the ground it shows through
    it half tinted with the ground's colour; above it, the asset is drawn as it is."""
    if not look:
        return '    cls(rgb(24, 28, 36))\n','','',('rgb(224, 230, 240)','rgb(140, 165, 190)')
    sky = look['background']
    clear = f'    cls({rgb_literal(sky[0])})\n'
    if len(sky) == 2:
        clear += f'    rect_grad(0, 0, 320, 240, {rgb_literal(sky[0])}, {rgb_literal(sky[1])}, -1)\n    ui_flush()\n'
    before = after = ''
    if look['ground']:
        before = f'    {ground}\n    ot_flush()\n    GPU_ZCLEAR = 0\n'
        after = f'    {tint}\n'
    luma = sum(.299*c[0]+.587*c[1]+.114*c[2] for c in sky)/len(sky)
    colours = ('rgb(28, 34, 44)','rgb(70, 86, 104)') if luma > LIGHT else ('rgb(224, 230, 240)','rgb(140, 165, 190)')
    return clear,before,after,colours


def ground_half(bounds):
    """Half the side of the fitted views' ground (world units): it reaches about three camera
    distances past the asset, toward the horizon."""
    _,scale,radius = fitting(bounds)
    return (3*max(1,radius*2.6)+radius)/scale


def ground_bytes(center, half, colour_, tint=False):
    """A square of ground at y = 0 around (x, z) = center, half wide on each side: a checker of
    tiles of a power of two metres (1 m or more, at most GROUND_TILES along a side) aligned to the
    world's metres, in the ground's colour and that times GROUND_SHADE, double-sided. tint: half
    transparent (blend mode 0, half the background and half the face), the cart's third pass."""
    tile = 1.0
    while 2*half/tile > GROUND_TILES: tile *= 2
    x0,z0 = (math.floor((c-half)/tile)*tile for c in center)
    nx,nz = (max(1,math.ceil((c+half-o)/tile)) for c,o in zip(center,(x0,z0)))
    shade = tuple(round(n*GROUND_SHADE) for n in colour_)
    mesh = meshlib.Mesh()
    index = {}
    for i in range(nx+1):
        for k in range(nz+1):
            index[i,k] = mesh.vertex(x0+i*tile,0.0,z0+k*tile)
    flags = meshlib.DOUBLE|(meshlib.SEMI if tint else 0)
    for i in range(nx):
        for k in range(nz):
            c = meshlib.rgb(*(colour_ if (i+k+int(x0/tile)+int(z0/tile))%2 == 0 else shade))
            mesh.quad([index[i,k],index[i+1,k],index[i,k+1],index[i+1,k+1]],[c],flags=flags,blend=0)
    return mesh.pack()


def ground_files(look, bounds, center=None, half=None, prefix='preview'):
    """{PREFIX_ground.bin, PREFIX_ground_tint.bin} for a look with a ground, else {}."""
    if not look or not look['ground']: return {}
    lo,hi = bounds['min'],bounds['max']
    center = center or ((lo[0]+hi[0])/2,(lo[2]+hi[2])/2)
    half = half or ground_half(bounds)
    return {f'{prefix}_ground.bin':ground_bytes(center,half,look['ground']),
            f'{prefix}_ground_tint.bin':ground_bytes(center,half,look['ground'],True)}


def shoot(directory, stem, code, compiler, runner, view):
    """Compile and run one preview cart: (pixels, the last presented frame's statistics)."""
    stem = Path(directory)/stem
    stem.with_suffix('.akr').write_text(code)
    native.run([compiler,stem.with_suffix('.akr'),'-o',stem.with_suffix('.mei')],'/preview',error=AssetError)
    native.run([runner,stem.with_suffix('.mei'),'--frames','4','--dump',stem.with_suffix('.ppm'),
                '--gpu-stats',stem.with_suffix('.csv')],'/preview',error=AssetError)
    pixels = native.read_ppm(stem.with_suffix('.ppm'),'/preview',error=AssetError)
    latest = native.last_frame_stats(stem.with_suffix('.csv'))
    if latest is None:
        raise AssetError('/preview',f'No presented frame for {view}.')
    return pixels,latest


def frame_share(stats, budgets):
    """The frame's CPU and GPU cycles and their share of the frame budgets (src/core/mei.h)."""
    return {'cpu_cycles':stats['cpu_cycles'],'gpu_cycles':stats['gpu_cycles'],
            'cpu_frame_percent':round(100*stats['cpu_cycles']/budgets['cpu'],1),
            'gpu_frame_percent':round(100*stats['gpu_cycles']/budgets['gpu'],1)}


def render(directory, name, bounds, compiler, runner, load=False, depth=False, perspective=None, failing=False,
           look=None):
    directory = Path(directory).resolve()
    native.require('/preview',(compiler,runner),TOOLS_HINT,error=AssetError)
    budgets = native.frame_budgets()
    images, reports = [],[]
    for filename,data in ground_files(look,bounds).items(): (directory/filename).write_bytes(data)
    for view,yaw,pitch in VIEWS:
        code = source(name,bounds,yaw,pitch,view,load=load,depth=depth,perspective=perspective,failing=failing,
                      look=look)
        pixels,latest = shoot(directory,f'view_{view}',code,compiler,runner,view)
        (directory/f'view_{view}.png').write_bytes(png_bytes(320,240,pixels))
        images.append(pixels)
        reports.append({'view':view,'image':f'view_{view}.png','stats':latest,'cost':frame_share(latest,budgets)})
    contact = directory/'contact.png'
    contact.write_bytes(native.contact_sheet(images))
    result = {'contact':str(contact),'views':reports}
    if look: result['look'] = look_report(look)
    if failing: result['failing'] = True
    return result


# ---- cameras at world scale (preview --camera, --cameras, --part, --closeups)

EYE_HEIGHT = 1.6        # a standing player's eye above the asset's base, for the eye_level close-up
SEGMENTS = 4            # at most this many close-ups along the longest axis


def look(eye, target):
    """(yaw, pitch) in radians of camera_look() at eye looking at target (stdlib/render.akr:
    forward = (sin yaw cos pitch, sin pitch, cos yaw cos pitch))."""
    d = [t-e for t,e in zip(target,eye)]
    if math.hypot(*d) < 1e-6:
        raise AssetError('/arguments/camera','The camera\'s eye and target are the same point.')
    return math.atan2(d[0],d[2]),math.atan2(d[1],math.hypot(d[0],d[2]))


def camera(name, eye, target=None, yaw=None, pitch=None, path='/arguments/camera'):
    """A camera view: eye (world units, the asset's own coordinates) and either a target or yaw and
    pitch in degrees (yaw 0 looks along +Z, positive turns toward +X; positive pitch looks up)."""
    if not re.fullmatch(r'[a-z0-9_]{1,40}',name or ''):
        raise AssetError(path,f'Camera name {name!r}: a camera name uses lowercase letters, digits and underscores '
                              '(at most 40).')
    numbers = list(eye)+list(target or [])+[n for n in (yaw,pitch) if n is not None]
    if len(eye) != 3 or (target is not None and len(target) != 3) or \
            not all(isinstance(n,(int,float)) and not isinstance(n,bool) and math.isfinite(n) and abs(n) < 30000 for n in numbers):
        raise AssetError(path,'A camera has an eye [x, y, z] and a target [x, y, z], or yaw and pitch in degrees.')
    if target is not None:
        y,p = look(eye,target)
    elif yaw is not None and pitch is not None:
        if not -90 <= pitch <= 90:
            raise AssetError(path,'Pitch is -90 to 90 degrees.')
        y,p = math.radians(yaw),math.radians(pitch)
    else:
        raise AssetError(path,'A camera has an eye [x, y, z] and a target [x, y, z], or yaw and pitch in degrees.')
    return {'name':name,'eye':[float(n) for n in eye],'yaw':y,'pitch':p,
            **({'target':[float(n) for n in target]} if target is not None else {})}


def parse_camera(text, index):
    """--camera [NAME=]EX,EY,EZ:TX,TY,TZ (eye and target) or [NAME=]EX,EY,EZ@YAW,PITCH (degrees)."""
    path = '/arguments/camera'
    name,_,spec = text.rpartition('=')
    name = name or f'camera{index+1}'
    usage = (f'Cannot read camera {text!r}: give NAME=EX,EY,EZ:TX,TY,TZ (eye and target) or '
             'NAME=EX,EY,EZ@YAW,PITCH (degrees).')
    # Only the numbers are parsed here; camera() checks the rest (the name, the eye and target)
    # and its own message says what is wrong, so an AssetError from it is not replaced by this
    # usage line (AssetError is a ValueError).
    try:
        if ':' in spec:
            eye,target = spec.split(':')
            eye,target = [float(n) for n in eye.split(',')],[float(n) for n in target.split(',')]
            angles = None
        elif '@' in spec:
            eye,angles = spec.split('@')
            yaw,pitch = (float(n) for n in angles.split(','))
            eye,angles = [float(n) for n in eye.split(',')],(yaw,pitch)
        else:
            raise AssetError(path,usage)
    except AssetError:
        raise
    except ValueError as error:
        raise AssetError(path,usage) from error
    if angles is None:
        return camera(name,eye,target,path=path)
    return camera(name,eye,yaw=angles[0],pitch=angles[1],path=path)


def cameras_file(value):
    """--cameras FILE: [{"name", "eye", "target"} or {"name", "eye", "yaw", "pitch"}, ...]."""
    if not isinstance(value,list):
        raise AssetError('/cameras','A cameras file is a JSON list of {"name", "eye", "target"} or {"name", "eye", "yaw", "pitch"}.')
    out = []
    for k,item in enumerate(value):
        where = f'/cameras/{k}'
        if not isinstance(item,dict) or set(item)-{'name','eye','target','yaw','pitch'} or 'eye' not in item:
            raise AssetError(where,'A camera is {"name", "eye", "target"} or {"name", "eye", "yaw", "pitch"}.')
        if not isinstance(item['eye'],list) or not isinstance(item.get('target',[]),list):
            raise AssetError(where,'eye and target are [x, y, z].')
        out.append(camera(item.get('name',f'camera{k+1}'),item['eye'],item.get('target'),item.get('yaw'),item.get('pitch'),where))
    return out


def framing(lo, hi, yaw, pitch, name, margin=1.15):
    """A camera looking at the box lo..hi from direction (yaw, pitch), as close as shows all of it
    in Mei's 60-degree view."""
    center = [(a+b)/2 for a,b in zip(lo,hi)]
    radius = max(0.05,math.sqrt(sum(((b-a)/2)**2 for a,b in zip(lo,hi))))
    distance = radius/math.sin(math.radians(30))*margin
    forward = (math.sin(yaw)*math.cos(pitch),math.sin(pitch),math.cos(yaw)*math.cos(pitch))
    eye = [c-f*distance for c,f in zip(center,forward)]
    return camera(name,eye,center)


def part_camera(parts, part_id, decals=()):
    """--part ID: the part's bounds framed from the isometric direction; a decal's id (PART/ID, as
    the report's decals name them) frames the decal face on, from outside its face."""
    found = [p for p in parts if p['id'] == part_id]
    decal = next((d for d in decals or () if d['id'] == part_id),None)
    if not found and decal:
        n = decal['normal']
        # look along -normal: forward = (sin yaw cos pitch, sin pitch, cos yaw cos pitch)
        yaw, pitch = math.atan2(-n[0],-n[2]) if abs(n[1]) < 0.999 else 0.0, math.asin(max(-1,min(1,-n[1])))
        if abs(n[1]) >= 0.999: pitch = -1.45 if n[1] > 0 else 1.45     # nearly straight down (up) at a cap
        return framing(decal['bounds']['min'],decal['bounds']['max'],yaw,pitch,
                       'decal_'+re.sub(r'[^a-z0-9_]','_',part_id)[:34],margin=1.6)
    if not found:
        known = ', '.join(sorted({p['id'] for p in parts})[:40])
        more = f' Decals: {", ".join(d["id"] for d in decals[:20])}.' if decals else ''
        raise AssetError('/arguments/part',f'No part {part_id!r}. Parts: {known}.{more}')
    lo = [min(p['bounds']['min'][k] for p in found) for k in range(3)]
    hi = [max(p['bounds']['max'][k] for p in found) for k in range(3)]
    return framing(lo,hi,VIEWS[0][1],VIEWS[0][2],'part_'+re.sub(r'[^a-z0-9_]','_',part_id)[:35])


def in_view(eye, target, points, margin=1.1):
    """Whether every point lies inside Mei's view (60 degrees high, 4:3) from eye looking at target,
    margin times inside its edges."""
    yaw,pitch = look(eye,target)
    forward = (math.sin(yaw)*math.cos(pitch),math.sin(pitch),math.cos(yaw)*math.cos(pitch))
    right = (math.cos(yaw),0.0,-math.sin(yaw))
    up = (-math.sin(pitch)*math.sin(yaw),math.cos(pitch),-math.sin(pitch)*math.cos(yaw))
    high = math.tan(math.radians(30))/margin
    wide = high/0.75
    for p in points:
        d = [a-b for a,b in zip(p,eye)]
        z = sum(a*b for a,b in zip(d,forward))
        if z < 0.2: return False
        if abs(sum(a*b for a,b in zip(d,up))) > high*z or abs(sum(a*b for a,b in zip(d,right))) > wide*z: return False
    return True


def closeups(bounds):
    """The automatic close-ups: eye_level, a player's eye 1.6 units above the ground in front of
    the asset (on its -Z side), looking at the middle of its front, as far back as shows all of
    its bounds; and, for an asset more than 1.5 times as long along one axis as across the others,
    up to 4 close-ups along that axis (closeup_1, ...), each framing one segment from the front
    (from +X when the long axis is Z), 15 degrees above. The ground is y = 0 when the asset
    reaches below it (a post sunk into the ground), else the asset's base."""
    lo,hi = bounds['min'],bounds['max']
    size = [b-a for a,b in zip(lo,hi)]
    center = [(a+b)/2 for a,b in zip(lo,hi)]
    base = 0.0 if lo[1] < 0 < hi[1] else lo[1]
    eye_y = base+EYE_HEIGHT
    half = max(size[0],size[1])/2
    back = max(2.0,half/math.tan(math.radians(30))*1.15)
    target = [center[0],center[1],lo[2]]
    corners = [(x,y,z) for x in (lo[0],hi[0]) for y in (lo[1],hi[1]) for z in (lo[2],hi[2])]
    for _ in range(60):
        if in_view([center[0],eye_y,lo[2]-back],target,corners): break
        back *= 1.1
    shots = [camera('eye_level',[center[0],eye_y,lo[2]-back],target)]
    axis = max(range(3),key=lambda k:(size[k],-k))
    across = max(max(s for k,s in enumerate(size) if k != axis),0.25)
    count = min(SEGMENTS,math.ceil(size[axis]/(1.5*across)-1e-9))
    if count >= 2:
        yaw = -math.pi/2 if axis == 2 else 0.0          # from +X for a Z-long asset, else from -Z
        for k in range(count):
            a,b = list(lo),list(hi)
            a[axis],b[axis] = lo[axis]+size[axis]*k/count,lo[axis]+size[axis]*(k+1)/count
            shots.append(framing(a,b,yaw,math.radians(-15),f'closeup_{k+1}'))
    return shots


def camera_source(name, view, load=False, depth=False, perspective=None, failing=False, draw=True, far=None, look=None):
    """A cart drawing the asset at world scale, placed at the origin with yaw 0 as mesh_at() places
    it, from the view's eye, yaw and pitch. No HUD text, so its cost is the asset's and the
    frame's clear (and the look's background and ground); draw=False leaves the asset out (the
    baseline)."""
    f = lambda n: f'{n:.7f}'
    init = f'fn init() {{ asset_{name}_load() }}\n\n' if load else ''
    ground = bool(look and look['ground'])
    depth = depth or ground
    perspective = depth if perspective is None else perspective or depth
    imports = f'import "{name}.akr"\n'+DEPTH.cart_import(depth,perspective)
    if ground:
        imports += 'embed CAMERA_GROUND: Mesh = "camera_ground.bin"\n' \
                   'embed CAMERA_GROUND_TINT: Mesh = "camera_ground_tint.bin"\n'
    modes = DEPTH.cart_lines(depth,perspective)
    eye = ', '.join(f(n) for n in view['eye'])
    mesh = f'    mesh_at(ASSET_{name.upper()}, vec3(0.0, 0.0, 0.0), 0.0)\n' if draw else ''
    clear,before,after,_ = look_passes(look,'mesh(CAMERA_GROUND)','mesh(CAMERA_GROUND_TINT)')
    return f'''// Generated by Mei Asset Kit. A camera view of the exported mesh at world scale.
cart "Asset camera"
{imports}
{init}fn draw() {{
{clear}{modes}    camera_clip(0.1, {f(far)})
    camera_look(vec3({eye}), {f(view['yaw'])}, {f(view['pitch'])})
{before}{mesh}{after}{FAILED_BANNER if failing else ''}}}
'''


def camera_ground(bounds, views):
    """(center, half) of the camera views' ground: around the asset, reaching 20 units or three
    times the asset's size past it, and past every eye."""
    lo,hi = bounds['min'],bounds['max']
    center = ((lo[0]+hi[0])/2,(lo[2]+hi[2])/2)
    size = max(hi[0]-lo[0],hi[2]-lo[2])
    reach = max([abs(v['eye'][0]-center[0]) for v in views]+[abs(v['eye'][2]-center[1]) for v in views])
    return center,max(20.0,3*size)+reach


def far_for(view, bounds):
    """Far clip for a view: past the farthest corner of the asset's bounds."""
    lo,hi = bounds['min'],bounds['max']
    corners = [(x,y,z) for x in (lo[0],hi[0]) for y in (lo[1],hi[1]) for z in (lo[2],hi[2])]
    return max(2.0,max(math.dist(view['eye'],c) for c in corners)+1)


def render_cameras(directory, name, bounds, views, compiler, runner, load=False, depth=False, perspective=None,
                   upscale=2, failing=False, look=None):
    """Each view rendered at world scale into camera_NAME.png (upscale times 320 x 240), the
    sheet cameras.png, and each view's frame cost, and the asset's share of it: the view minus
    a baseline frame that clears (and draws the look's ground) and draws no asset."""
    directory = Path(directory).resolve()
    native.require('/preview',(compiler,runner),TOOLS_HINT,error=AssetError)
    budgets = native.frame_budgets()
    far = lambda view: far_for(view,bounds)
    if look and look['ground']:
        center,half = camera_ground(bounds,views)
        for filename,data in ground_files(look,bounds,center,half,'camera').items(): (directory/filename).write_bytes(data)
        # the far clip past the ground's farthest corner
        far = lambda view: max(far_for(view,bounds),math.hypot(abs(view['eye'][0]-center[0])+half,
                                                               abs(view['eye'][2]-center[1])+half,view['eye'][1])+1)
    base_view = views[0]
    _,baseline = shoot(directory,'camera_baseline',camera_source(name,base_view,load,depth,perspective,failing,False,
                                                                 far(base_view),look),compiler,runner,'baseline')
    images,reports = [],[]
    for view in views:
        code = camera_source(name,view,load,depth,perspective,failing,True,far(view),look)
        pixels,latest = shoot(directory,f'camera_{view["name"]}',code,compiler,runner,view['name'])
        big = native.upscaled(pixels,upscale)
        (directory/f'camera_{view["name"]}.png').write_bytes(png_bytes(320*upscale,240*upscale,big))
        images.append(big)
        asset = {'cpu_cycles':latest['cpu_cycles']-baseline['cpu_cycles'],'gpu_cycles':latest['gpu_cycles']-baseline['gpu_cycles']}
        reports.append({'view':view['name'],'image':f'camera_{view["name"]}.png',
                        'eye':[round(n,4) for n in view['eye']],
                        **({'target':view['target']} if 'target' in view else {}),
                        'yaw_degrees':round(math.degrees(view['yaw']),2),'pitch_degrees':round(math.degrees(view['pitch']),2),
                        'triangles':latest['tris'],'stats':latest,
                        'cost':{**frame_share(latest,budgets),
                                'asset_cpu_cycles':asset['cpu_cycles'],'asset_gpu_cycles':asset['gpu_cycles'],
                                'asset_cpu_frame_percent':round(100*asset['cpu_cycles']/budgets['cpu'],1),
                                'asset_gpu_frame_percent':round(100*asset['gpu_cycles']/budgets['gpu'],1)}})
    sheet = directory/'cameras.png'
    sheet.write_bytes(native.tile_sheet(images,320*upscale,240*upscale,min(2,len(images))))
    return {'contact':str(sheet),'upscale':upscale,'budgets':budgets,
            'baseline':{'cpu_cycles':baseline['cpu_cycles'],'gpu_cycles':baseline['gpu_cycles']},
            'views':reports,**({'failing':True} if failing else {})}
