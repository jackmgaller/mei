def shore_r(a):
    r = 25.0 + 2.4 * math.sin(2 * a + 0.7) + 1.4 * math.sin(3 * a + 2.1) + 0.9 * math.sin(5 * a + 0.4)
    r += 14.0 * bump(angdiff(a, A_BRIDGE) / 0.085)
    r += 9.0 * bump(angdiff(a, A_RIVER) / 0.10)
    r += 2.5 * bump(angdiff(a, A_LILY + 0.25) / 0.35)        # the lily cove
    return r


def apos(a, r, y=0.0):
    return (r * math.sin(a), y, r * math.cos(a))


