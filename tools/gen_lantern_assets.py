def material(name, u, v, img, cols, emissive=(), lit=None, glow_col=(255, 196, 110), atlas=None):
    """cols: 15 albedo colours for indices 1..15. emissive: indices that glow at night."""
    (atlas or A0).put(u, v, img)
    assert len(cols) == 15, (name, len(cols))
    keys = []
    for k in range(4):
        pal = [(0, 0, 0)]
        for i, c in enumerate(cols):
            ii = i + 1
            L = LIGHT[k] if lit is None else lit[k]
            col = tuple(c[j] * L[j] for j in range(3))
            if ii in emissive:
                g = GLOW[k]
                col = lerp3(col, glow_col, g)
            pal.append(col)
        keys.append(pal)
    MATS[name] = dict(u=u, v=v, w=img.shape[1], h=img.shape[0], keys=keys, src=len(MAT_ORDER))
    MAT_ORDER.append(name)


