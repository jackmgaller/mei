class Atlas:
    def __init__(self):
        self.idx = np.zeros((256, 256), np.uint8)

    def put(self, u, v, img):
        h, w = img.shape
        self.idx[v:v + h, u:u + w] = img

    def pack(self):
        a = self.idx
        return (a[:, 0::2] | (a[:, 1::2] << 4)).astype(np.uint8).tobytes()


