def deck(length, width, y, seg=1.6, thick=0.12, posts=True, post_every=2.0, x_off=0.0, sag=0.0, wob=0.0):
    """A plank deck in local space: along +Z from z=0 to z=length, x in +-width/2."""
    out = []
    nseg = max(1, int(round(length / seg)))
    w2 = width / 2
    for s_ in range(nseg):
        z0 = length * s_ / nseg
        z1 = length * (s_ + 1) / nseg
        yy0 = y + wob * math.sin(s_ * 2.1)
        yy1 = y + wob * math.sin((s_ + 1) * 2.1)
        # top: planks run across x, so u along x
        M = MATS['planks']
        uvs = [(M['u'], M['v'] + 31), (M['u'] + 31, M['v'] + 31), (M['u'], M['v']), (M['u'] + 31, M['v'])]
        # rotate: v along z (boards across the deck)
        uvs = [(M['u'], M['v']), (M['u'], M['v'] + 31), (M['u'] + 31, M['v']), (M['u'] + 31, M['v'] + 31)]
        tint = [lit_tint((0, 1, 0), 1.0, 0.95 + 0.1 * ((s_ * 37) % 3) / 2)] * 4
        out.append(Face([(-w2 + x_off, yy0, z0), (w2 + x_off, yy0, z0), (-w2 + x_off, yy1, z1), (w2 + x_off, yy1, z1)],
                        uvs, tint, 'planks', (0, 1, 0)))
        # sides
        lo = lit_tint((0, 0, 0), 0.6)
        hi = lit_tint((1, 0.2, 0), 0.85)
        for sx in (-1, 1):
            x = sx * w2 + x_off
            n = (sx, 0, 0)
            out.append(Face([(x, yy0 - thick, z0), (x, yy1 - thick, z1), (x, yy0, z0), (x, yy1, z1)],
                            plank_uv(), [lo, lo, hi, hi], 'planks', n))
    # end cap
    lo = lit_tint((0, 0, 0), 0.6)
    out.append(Face([(-w2 + x_off, y - thick, length), (w2 + x_off, y - thick, length), (-w2 + x_off, y, length),
                     (w2 + x_off, y, length)], plank_uv(), [lo] * 4, 'planks', (0, 0, 1)))
    if posts:
        z = 0.3
        while z < length:
            for sx in (-1, 1):
                x = sx * (w2 - 0.08) + x_off
                out += box_faces(x - 0.1, -0.1, z - 0.1, x + 0.1, y - thick, z + 0.1, 'log', top=False, base=0.8,
                                 refl=False, lod=False)
            z += post_every
    return out


def lantern_post(x, z, y, h=1.5, side=0):
    """A wooden post with a hanging paper lantern; returns faces and the lantern centre."""
    out = box_faces(x - 0.06, y, z - 0.06, x + 0.06, y + h, z + 0.06, 'log', base=0.9, top=False, lod=False)
    lx = x + 0.3 * side
    ly = y + h - 0.3
    if side:
        out += box_faces(min(x, lx) - 0.03, y + h - 0.06, z - 0.03, max(x, lx) + 0.03, y + h, z + 0.03, 'log',
                         base=0.9, sides='ns', lod=False)
    pu = [(192, 55), (207, 55), (192, 32), (207, 32)]
    out += box_faces(lx - 0.11, ly - 0.16, z - 0.11, lx + 0.11, ly + 0.16, z + 0.11, 'paper', uvs=pu, refl=False, lod=False,
                     top=False)
    out += sw_box(lx - 0.07, ly + 0.16, z - 0.07, lx + 0.07, ly + 0.2, z + 0.07, 10, refl=False, lod=False)
    return out, (lx, ly, z)


