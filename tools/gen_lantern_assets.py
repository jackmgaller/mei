def bump(x):
    return math.exp(-x * x)


def angdiff(a, b):
    d = (a - b + math.pi) % (2 * math.pi) - math.pi
    return d


A_BRIDGE = 0.0
A_RIVER = -1.80
A_LILY = 1.05
A_PIER = math.pi
A_REEDS = -1.42
