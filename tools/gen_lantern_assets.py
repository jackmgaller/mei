def fish_image(sp, seed):
    """Renders a 64x32 index image (fish facing left)."""
    S = 8
    W, H = 64 * S, 32 * S
    sh = sp['shape']
    L = sh['L'] * W * 0.86
    Hh = sh['H'] * H
    x0 = W * 0.06
    cy = H * 0.5
    mask = Image.new('L', (W, H), 0)
    fins = Image.new('L', (W, H), 0)
    dm = ImageDraw.Draw(mask)
    df = ImageDraw.Draw(fins)
    body_len = L * (1 - sh['tail'] * 0.6)
    top, bot = [], []
    for k in range(65):
        t = k / 64
        # thickness profile: blunt head, taper to the tail stalk
        prof = (math.sin(math.pi * min(1, t * 1.15) ** (0.6 + sh['snout'] * 0.5)) ** 0.8)
        prof = max(prof, 0.18 if t > 0.8 else 0)
        x = x0 + t * body_len
        top.append((x, cy - Hh * 0.5 * prof * 1.05))
        bot.append((x, cy + Hh * 0.5 * prof * 0.95))
    dm.polygon(top + bot[::-1], fill=255)
    tx = x0 + body_len - 4 * S
    tl = sh['tail'] * W * 0.42
    df.polygon([(tx, cy - 2 * S), (tx + tl, cy - Hh * 0.62), (tx + tl * 0.72, cy), (tx + tl, cy + Hh * 0.62), (tx, cy + 2 * S)], fill=255)
    d = sh['dorsal']
    if d == 'spiny':
        df.polygon([(x0 + body_len * 0.3, cy - Hh * 0.42), (x0 + body_len * 0.38, cy - Hh * 0.82), (x0 + body_len * 0.5, cy - Hh * 0.75),
                    (x0 + body_len * 0.62, cy - Hh * 0.8), (x0 + body_len * 0.75, cy - Hh * 0.38)], fill=255)
    elif d == 'rear':
        df.polygon([(x0 + body_len * 0.7, cy - Hh * 0.35), (x0 + body_len * 0.82, cy - Hh * 0.9), (x0 + body_len * 0.92, cy - Hh * 0.3)], fill=255)
        df.polygon([(x0 + body_len * 0.72, cy + Hh * 0.35), (x0 + body_len * 0.84, cy + Hh * 0.85), (x0 + body_len * 0.93, cy + Hh * 0.3)], fill=255)
    elif d == 'long':
        df.polygon([(x0 + body_len * 0.35, cy - Hh * 0.45), (x0 + body_len * 0.45, cy - Hh * 0.72), (x0 + body_len * 0.85, cy - Hh * 0.5),
                    (x0 + body_len * 0.9, cy - Hh * 0.25)], fill=255)
    elif d == 'tall':
        df.polygon([(x0 + body_len * 0.42, cy - Hh * 0.45), (x0 + body_len * 0.5, cy - Hh * 0.95), (x0 + body_len * 0.66, cy - Hh * 0.4)], fill=255)
        df.polygon([(x0 + body_len * 0.55, cy + Hh * 0.4), (x0 + body_len * 0.66, cy + Hh * 0.8), (x0 + body_len * 0.86, cy + Hh * 0.3)], fill=255)
    elif d == 'mid':
        df.polygon([(x0 + body_len * 0.42, cy - Hh * 0.42), (x0 + body_len * 0.5, cy - Hh * 0.82), (x0 + body_len * 0.62, cy - Hh * 0.4)], fill=255)
        df.polygon([(x0 + body_len * 0.8, cy - Hh * 0.28), (x0 + body_len * 0.84, cy - Hh * 0.5), (x0 + body_len * 0.88, cy - Hh * 0.25)], fill=255)
    else:
        df.polygon([(x0 + body_len * 0.36, cy - Hh * 0.4), (x0 + body_len * 0.42, cy - Hh * 0.7), (x0 + body_len * 0.5, cy - Hh * 0.38)], fill=255)
    # pectoral and pelvic fins
    df.polygon([(x0 + body_len * 0.28, cy + Hh * 0.1), (x0 + body_len * 0.42, cy + Hh * 0.38), (x0 + body_len * 0.36, cy + Hh * 0.08)], fill=255)
    df.polygon([(x0 + body_len * 0.45, cy + Hh * 0.4), (x0 + body_len * 0.52, cy + Hh * 0.7), (x0 + body_len * 0.58, cy + Hh * 0.4)], fill=255)
    if sh.get('whiskers'):
        for k in (-1, 1):
            df.line([(x0 + 3 * S, cy + 1 * S), (x0 - 1 * S, cy + (6 + 4 * k) * S)], fill=255, width=S)
    small = lambda im: np.asarray(im.resize((64, 32), Image.BOX), np.float32) / 255
    mb = small(mask)
    mf = small(fins)
    # shading: vertical position within the body
    ys = (np.arange(32)[:, None] + 0.5 - 16) / (Hh / S * 0.5 + 1e-6)
    xs_ = (np.arange(64)[None, :] + 0.5 - x0 / S) / (body_len / S)
    r = np.random.default_rng(seed)
    idx = np.zeros((32, 64), np.uint8)
    body = mb > 0.45
    fin = (mf > 0.45) & ~body
    shade = np.broadcast_to(np.clip((ys + 1) / 2, 0, 1), (32, 64))   # 0 top .. 1 bottom
    xs_ = np.broadcast_to(xs_, (32, 64))
    lvl = np.clip((shade * 6.2).astype(int), 0, 6)
    tbl = np.array([2, 3, 4, 5, 6, 7, 8], np.uint8)
    idx[body] = tbl[lvl[body]]
    m = sp['marks']
    if m == 'bars':
        bars = (np.sin(xs_ * 2 * math.pi * 3.5) > 0.45) & (shade < 0.75)
        idx[body & bars] = 9
    elif m == 'spots':
        sp_ = value_noise(64, 32, 16, 8, seed + 3) > 0.68
        idx[body & sp_ & (shade < 0.8)] = 9
    elif m == 'scales':
        sc = ((np.arange(64)[None, :] + (np.arange(32)[:, None] // 3) * 2) % 4 == 0) & ((np.arange(32)[:, None]) % 3 == 0)
        idx[body & sc & (shade < 0.8)] = 9
    elif m == 'mottle':
        mt = value_noise(64, 32, 12, 6, seed + 5) > 0.6
        idx[body & mt & (shade < 0.55)] = 1
        dots = value_noise(64, 32, 24, 12, seed + 6) > 0.8
        idx[body & dots & (shade > 0.3) & (shade < 0.75)] = 9
    elif m == 'band':
        band = (np.abs(shade - 0.5) < 0.1) & (xs_ > 0.15) & (xs_ < 0.92)
        idx[body & band] = 9
        dots = value_noise(64, 32, 20, 10, seed + 7) > 0.74
        idx[body & dots & (shade < 0.45)] = 1
    elif m == 'sheen':
        sh_ = (np.sin(xs_ * 9 + shade * 3) > 0.7) & (shade > 0.25) & (shade < 0.65)
        idx[body & sh_] = 10
    elif m == 'patches':
        pt = value_noise(64, 32, 5, 3, seed + 9) > 0.55
        idx[body & pt & (shade < 0.85)] = 10
    idx[fin] = np.where(mf[fin] > 0.75, 11, 12)
    # outline: transparent neighbour
    solid = idx > 0
    edge = solid & ~(np.roll(solid, 1, 0) & np.roll(solid, -1, 0) & np.roll(solid, 1, 1) & np.roll(solid, -1, 1))
    idx[edge & body] = 1
    # gill line and eye
    gx = int(x0 / S + body_len / S * 0.24)
    for y in range(32):
        if body[y, gx] and abs(y - 16) < Hh / S * 0.32:
            idx[y, gx] = 1
    ex = int(x0 / S + body_len / S * 0.11) + 1
    ey = int(16 - Hh / S * 0.1)
    idx[ey - 1:ey + 2, ex - 1:ex + 2] = 13
    idx[ey, ex] = 14
    idx[ey - 1, ex - 1] = 15
    return idx


def fish_pal(c):
    back, flank, belly, mark, fin = c['back'], c['flank'], c['belly'], c['mark'], c['fin']
    sh = [lerp3(back, flank, t) for t in (0.0, 0.35, 0.7, 1.0)] + [lerp3(flank, belly, 0.4)]
    outline = tuple(v * 0.35 for v in back)
    return [outline] + sh + [lerp3(flank, belly, 0.75), belly, mark, lerp3(mark, (255, 255, 255), 0.5),
                             fin, lerp3(fin, back, 0.45), (250, 250, 240), (16, 16, 24), (255, 255, 255)]


