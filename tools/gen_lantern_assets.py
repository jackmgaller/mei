def box_faces(x0, y0, z0, x1, y1, z1, mat, uvs=None, top=True, bottom=False, sides='nsew', base=1.0, refl=True,
              topmat=None, lod=True):
    """Axis-aligned box faces. uvs: corner uvs for every face (default: whole cell)."""
    out = []
    uv = uvs or cell_uv(mat)
    tm = topmat or mat
    tuv = uvs or cell_uv(tm)
    if top:
        out.append(Face([(x0, y1, z0), (x1, y1, z0), (x0, y1, z1), (x1, y1, z1)], tuv,
                        [lit_tint((0, 1, 0), 1, base)] * 4, tm, (0, 1, 0), refl=refl, lo=lod))
    if bottom:
        out.append(Face([(x0, y0, z0), (x1, y0, z0), (x0, y0, z1), (x1, y0, z1)], uv,
                        [lit_tint((0, -1, 0), 0.7, base)] * 4, mat, (0, -1, 0), refl=refl, lo=lod))
    lo = lit_tint((0, 0, 0), 0.75, base)
    hi = None
    if 's' in sides:
        n = (0, 0, -1); hi = lit_tint(n, 1, base)
        out.append(Face([(x0, y0, z0), (x1, y0, z0), (x0, y1, z0), (x1, y1, z0)], uv, [lo, lo, hi, hi], mat, n, refl=refl, lo=lod))
    if 'n' in sides:
        n = (0, 0, 1); hi = lit_tint(n, 1, base)
        out.append(Face([(x1, y0, z1), (x0, y0, z1), (x1, y1, z1), (x0, y1, z1)], uv, [lo, lo, hi, hi], mat, n, refl=refl, lo=lod))
    if 'w' in sides:
        n = (-1, 0, 0); hi = lit_tint(n, 1, base)
        out.append(Face([(x0, y0, z1), (x0, y0, z0), (x0, y1, z1), (x0, y1, z0)], uv, [lo, lo, hi, hi], mat, n, refl=refl, lo=lod))
    if 'e' in sides:
        n = (1, 0, 0); hi = lit_tint(n, 1, base)
        out.append(Face([(x1, y0, z0), (x1, y0, z1), (x1, y1, z0), (x1, y1, z1)], uv, [lo, lo, hi, hi], mat, n, refl=refl, lo=lod))
    return out


def transform(faces, yaw, origin):
    """Rotates faces about +Y by yaw (turning +Z toward +X) and moves them to origin."""
    s, c = math.sin(yaw), math.cos(yaw)

    def tp(p):
        return (origin[0] + p[0] * c + p[2] * s, origin[1] + p[1], origin[2] - p[0] * s + p[2] * c)

    def tn(n):
        return (n[0] * c + n[2] * s, n[1], -n[0] * s + n[2] * c)
    out = []
    for f in faces:
        out.append(Face([tp(p) for p in f.pts], f.uvs, f.cols, f.mat, tn(f.n), f.flags, f.blend, f.refl, f.lo, f.hi))
    return out


