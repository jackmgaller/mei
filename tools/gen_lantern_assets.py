def in_village(a):
    return VILLAGE_A[0] - 0.1 < (a % (2 * math.pi)) < VILLAGE_A[1] + 0.1


def ring_height(a, k):
    if k == 0:
        return 0.0
    h = RING_H[k]
    if in_village(a) and 1 <= k <= 4:
        h = min(h, 0.42 + 0.08 * k)
    # the river mouth and the bridge inlet: low banks
    h *= 1 - 0.45 * bump(angdiff(a, A_RIVER) / 0.18)
    h += 0.25 * k / 5 * math.sin(a * 7 + k) + 0.15 * math.sin(a * 13 + 2 * k)
    return max(0.12 * k, h)


def lit_tint(n, ao=1.0, base=1.0):
    """Baked tint (0x808080 = unchanged) from a soft sky light and ambient occlusion."""
    sky = 0.62 + 0.38 * max(0.0, n[1]) + 0.12 * max(0.0, -n[0] * 0.6 + n[2] * 0.3)
    v = 128 * sky * ao * base
    return rgbw(v, v, v)


class Face:
    __slots__ = ('pts', 'uvs', 'cols', 'mat', 'flags', 'n', 'blend', 'refl', 'lo', 'hi')

    def __init__(self, pts, uvs, cols, mat, n, flags=0, blend=0, refl=True, lo=True, hi=True):
        self.pts, self.uvs, self.cols, self.mat, self.n = pts, uvs, cols, mat, n
        self.flags, self.blend, self.refl, self.lo, self.hi = flags, blend, refl, lo, hi


def sub(a, b):
    return tuple(a[i] - b[i] for i in range(3))


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def dot(a, b):
    return sum(a[i] * b[i] for i in range(3))


def norm(v):
    l = math.sqrt(dot(v, v)) or 1
    return tuple(c / l for c in v)


def emit(faces, mirror=False, centre=None, lo=False):
    """Builds a Mesh from logical faces. Corners are BL, BR, TL, TR (quads) as seen from
    the side the normal points to; the winding is fixed up from the normal. mirror: y -> -y
    and reflection palettes."""
    m = Mesh()
    vmap = {}

    def vid(p):
        key = tuple(round(c, 4) for c in p)
        if key not in vmap:
            vmap[key] = m.vertex(*p)
        return vmap[key]

    for f in faces:
        if mirror and not f.refl:
            continue
        if lo and not f.lo:
            continue
        if not lo and not f.hi:
            continue
        pts = list(f.pts)
        n = f.n
        if mirror:
            pts = [(p[0], 2 * WATER_Y - p[1], p[2]) for p in pts]
            n = (n[0], -n[1], n[2])
        uvs, cols = (list(f.uvs) if f.uvs else None), list(f.cols)
        c = cross(sub(pts[1], pts[0]), sub(pts[2], pts[0]))
        if dot(c, n) > 0:          # wrong winding: mirror the corner order
            if len(pts) == 4:
                order = [1, 0, 3, 2]
            else:
                order = [1, 0, 2]
            pts = [pts[i] for i in order]
            if uvs:
                uvs = [uvs[i] for i in order]
            cols = [cols[i] for i in order]
        mat = f.mat
        if isinstance(mat, str):
            pal = PALNUM[mat] + (REFL_OFF if mirror else 0)
            slot, fourbit = 0, True
        else:
            slot, fourbit, pal = mat
        if mirror:
            cols = [scale_tint(c, 0.92) for c in cols]
        idx = [vid(p) for p in pts]
        m.face(idx, cols, uvs, f.flags, slot=slot, four_bit=fourbit, palette=pal, blend=f.blend)
    return m


def scale_tint(c, k):
    r, g, b = c & 255, (c >> 8) & 255, (c >> 16) & 255
    return rgbw(r * k, g * k, b * k)


