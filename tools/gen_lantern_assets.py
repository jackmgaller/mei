def dock_basic(a, length, width, y, extra=None, lanterns_every=None, wob=0.0, post_every=2.0, end_lantern=True):
    R = shore_r(a)
    base = apos(a, R + 1.6)
    yaw = math.atan2(-base[0], -base[2])          # facing the lake centre
    f = deck(length + 1.6, width, y, wob=wob, post_every=post_every)
    lan = []
    if lanterns_every:
        # in lighting order: the far end first (in view), then back toward the shore
        for z in (length + 1.4, 3.2, 0.9):
            for side in (1, -1):
                lf, lp = lantern_post(side * (width / 2 - 0.1), z, y, side=-side)
                f += lf; lan.append(lp)
    elif end_lantern:
        lf, lp = lantern_post(width / 2 - 0.1, length + 1.2, y, side=-1)
        f += lf; lan.append(lp)
    if extra:
        ef, el = extra(length, width, y)
        f += ef; lan += el
    faces, lt = place(f, lan, yaw, (base[0], 0, base[2]))
    s, c = math.sin(yaw), math.cos(yaw)
    sz = length + 1.6 - 0.9
    stand = (base[0] + s * sz, y, base[2] + c * sz)
    return dict(stand=stand, yaw=yaw, faces=faces, lanterns=lt, base=base)


