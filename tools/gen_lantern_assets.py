def icon(name, fn, cols):
    S = 8
    im = Image.new('RGBA', (16 * S, 16 * S), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    fn(d, S)
    sm = im.resize((16, 16), Image.LANCZOS)
    a = np.asarray(sm, np.float32) / 255
    rgb = a[..., :3] * 255
    idx = np.zeros((16, 16), np.uint8)
    # map each pixel to the nearest palette colour (cols = list of up to 15 colours)
    pal = np.array(cols, np.float32)
    for y in range(16):
        for x in range(16):
            if a[y, x, 3] > 0.45:
                dd = ((pal - rgb[y, x]) ** 2).sum(axis=1)
                idx[y, x] = 1 + int(dd.argmin())
    n = len(icon_list)
    u, v = (n % 16) * 16, 64 + (n // 16) * 16
    A1.put(u, v, idx)
    ICONS[name] = (u, v, stat_pal(cols))
    icon_list.append(name)


