#!/usr/bin/env python3
"""Generates the model pack of the "Fall Line" cart (carts/fallline/README.md).

Writes, in carts/fallline/:
  art/          every mesh, texture slot and palette of carts/fallline/models/*/*.asset.json,
                packed together by `mei_assets.py pack` (texture slots 0-9, 4-bit palettes from
                0, 8-bit palettes from 14 down); the plane art (art/plane_*) is the slope
                engine's and is left alone
  assets.akr    the pack's embeds (every ASSET_*), the semi-transparent face ranges, and one
                loader, assets_load()

Faces whose material is tagged `glass` (the sled's canopy) are made semi-transparent in the
packed mesh (flag bit 3, blend mode 0, BLEND_HALF: half the scene behind, half the face): the
Asset Kit makes opaque faces only, and its Asset Checker judges them opaque, which with the depth
buffer is exact for everything but the glass itself (semi-transparent faces test depth and write
none, drawn after the opaque ones).

Recipes are whatever exists; one the kit rejects (a recipe still being written) is left out with
a warning and the rest packed. Prints the triangles of each recipe against the README's limits,
the VRAM, palettes and ROM used. Options: --dry-run (pack and print, write nothing);
--check DIR (a build directory with meic and mei-headless: compiles a probe cart that imports
the written assets.akr and draws every asset over snow, and saves its frames as PNGs in
DIR/fallline-assets/). Needs only the standard library (Pillow for the recipes' images and for
--check's PNGs)."""
import json
import re
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CART = ROOT/'carts'/'fallline'
ART = CART/'art'
HEADER = '// Generated by tools/gen_fallline_assets.py - do not edit.'

PACK_NAME = 'fl_pack'
PACK_SLOTS = '0-9'          # README: plane pages (10-15) are the slope engine's
PALETTE = 0                 # 4-bit palettes from 0 up
PALETTE8 = 14               # 8-bit palettes from 14 down (4-bit 224-239), if any texture is 8-bit
PLANE_PREFIX = 'plane_'     # art/plane_* belong to the slope engine

LIMITS = {'sled': 500, 'gate': 200, 'finish': 500, 'pine': 100, 'pylon': 60, 'marker': 40}
SEMI_TAG = 'glass'
BLEND_HALF = 0

sys.path.insert(0, str(ROOT/'tools'))


def recipes():
    """(model folder, path) of every recipe under models/."""
    out = []
    for folder in sorted((CART/'models').glob('*')):
        if folder.is_dir():
            out += [(folder.name, p) for p in sorted(folder.glob('*.asset.json'))]
    return out


def run_pack(found, work, skipped):
    """Packs `found` into `work`; a recipe the kit rejects is dropped (with its error in
    `skipped`) and the rest packed again. Returns the manifest, or None with nothing left."""
    while found:
        cmd = [sys.executable, str(ROOT/'tools'/'mei_assets.py'), 'pack', *[str(p) for _, p in found],
               '-o', str(work), '--name', PACK_NAME, '--slots', PACK_SLOTS,
               '--palette', str(PALETTE), '--palette8', str(PALETTE8)]
        run = subprocess.run(cmd, capture_output=True, text=True)
        try:
            result = json.loads(run.stdout)
        except json.JSONDecodeError:
            sys.exit(f'mei_assets.py pack failed:\n{run.stdout}\n{run.stderr}')
        if result.get('ok'):
            return json.loads((work/f'{PACK_NAME}.pack.json').read_text())
        errors = result.get('errors', [])
        bad = next((int(m.group(1)) for e in errors
                    for m in [re.match(r'/assets/(\d+)', e.get('path', ''))] if m), None)
        if bad is None:
            sys.exit('mei_assets.py pack failed:\n'+json.dumps(result, indent=2))
        _, path = found.pop(bad)
        skipped.append(f'{path.relative_to(CART)}: {errors[0].get("message", "")[:240]}')
    return None


def semi_faces(path):
    """Half-open runs of the recipe's exported faces whose material is tagged glass."""
    from assetkit.compiler import compile_recipe, face_runs
    recipe = json.loads(path.read_text())
    mesh, materials, _ = compile_recipe(recipe, path.parent)
    runs = face_runs(mesh, lambda f: materials[f.material].get('tag') == SEMI_TAG)
    return recipe['name'], runs, len(mesh.faces)


def make_semi(data, runs, faces):
    """The native mesh with the faces in `runs` semi-transparent (BLEND_HALF)."""
    data = bytearray(data)
    _, count, _, foff = struct.unpack_from('<HHII', data, 0)
    if count != faces:
        sys.exit(f'packed mesh has {count} faces, the recipe {faces}: cannot mark its glass')
    for a, b in runs:
        for i in range(a, b):
            data[foff+36*i] |= 8
            data[foff+36*i+1] = BLEND_HALF
    return bytes(data)


def owned_art():
    """The files in art/ this generator wrote (everything but the plane art)."""
    if not ART.exists():
        return []
    return [p for p in ART.iterdir() if p.is_file() and not p.name.startswith(PLANE_PREFIX)]


def floor_mesh():
    """A native mesh: a white floor 400 m square at y = 0, double-sided, its far edge tinted
    toward the sky (docs/LANGUAGE.md, "Mesh format")."""
    verts = [(-200, 0, -40), (200, 0, -40), (200, 0, 360), (-200, 0, 360)]
    near, far = 0xfaf6f0, 0xf0e2d0          # 0xBBGGRR
    data = struct.pack('<HHIII', 4, 2, 16, 16+16*4, 0)
    for x, y, z in verts:
        data += struct.pack('<iiii', x << 16, y << 16, z << 16, 1 << 16)
    for tri, cols in (((0, 1, 2), (near, near, far)), ((0, 2, 3), (near, far, far))):
        data += struct.pack('<BBBB', 16 | 1, 0, 0, 0)
        data += struct.pack('<HHHH', *tri, 0)
        data += struct.pack('<IIII', *cols, 0)
        data += struct.pack('<HHHH', 0, 0, 0, 0)
    return data


def probe(build, manifest):
    """Compiles and runs a cart that imports the written assets.akr (meic -I carts/fallline) and
    draws each asset on a white floor under a pale sky, from about where the game's camera
    sees it; saves each view as a PNG (2x)."""
    meic, run = Path(build)/'meic', Path(build)/'mei-headless'
    out = Path(build)/'fallline-assets'
    work = out/'probe'
    work.mkdir(parents=True, exist_ok=True)
    for p in out.glob('*.png'):
        p.unlink()
    for p in work.glob('f_*.ppm'):
        p.unlink()
    names = [a['name'] for a in manifest['assets']] if manifest else []
    # Per view: the asset, where it stands, its yaw, the eye, and the camera's yaw and pitch.
    views = []
    for n in names:
        if n == 'sled':
            views.append((n, '0.0, 0.0, 0.0', 'PI', '0.0, 1.9, -4.2', '0.0', '-0.30'))
            views.append((n, '0.0, 0.0, 0.0', 'PI - 0.35', '1.4, 1.2, -2.4', '-0.45', '-0.25'))
            views.append((n, '0.0, 0.0, 0.0', 'PI + 1.2', '0.0, 1.4, -3.2', '0.0', '-0.25'))
        elif n == 'finish':
            views.append((n, '0.0, 0.0, 30.0', '0.0', '0.0, 2.2, -4.0', '0.0', '0.08'))
            views.append((n, '0.0, 0.0, 12.0', '0.0', '2.0, 2.0, -2.0', '0.0', '0.30'))
        elif n == 'gate':
            views.append((n, '0.0, 0.0, 9.0', '0.0', '0.6, 2.0, -4.0', '0.0', '-0.02'))
            views.append((n, '0.0, 0.0, 40.0', '0.0', '0.6, 2.0, -4.0', '0.0', '-0.02'))
        else:
            views.append((n, '0.0, 0.0, 6.0', '0.0', '0.0, 1.8, -1.0', '0.0', '-0.05'))
    (work/'floor.bin').write_bytes(floor_mesh())
    lines = ['cart "Fall Line assets probe"', 'import "assets.akr"', 'import "depth.akr"', '',
             'embed FLOOR: Mesh = "floor.bin"', '',
             'var t: s32 = 0', '', 'fn init() { assets_load() }', '',
             'fn update() { t += 1 }', '',
             'fn draw() {', '    let view = t / 4', '    cls(rgb(150, 205, 245))',
             '    render_depth(true)', '    render_perspective(true)', '    camera_clip(0.1, 300.0)']
    for k, (n, at, yaw, eye, cy, cp) in enumerate(views):
        lines += [f'    if view == {k} {{',
                  f'        camera_look(vec3({eye}), {cy}, {cp})',
                  f'        mesh_at(ASSET_{n.upper()}, vec3({at}), {yaw})',
                  '    }']
    lines += ['    mesh(FLOOR)', '}', '']
    (work/'probe.akr').write_text('\n'.join(lines))
    r = subprocess.run([str(meic), str(work/'probe.akr'), '-o', str(work/'probe.mei'), '-I', str(CART)],
                       capture_output=True, text=True)
    if r.returncode:
        sys.exit(f'the probe cart does not compile:\n{r.stdout}{r.stderr}')
    r = subprocess.run([str(run), str(work/'probe.mei'), '--frames', str(4*len(views)+1), '--quiet',
                        '--dump-every', '4', str(work/'f'), '--dump-from', '2',
                        '--gpu-stats', str(work/'gpu.csv')], capture_output=True, text=True)
    if r.returncode:
        sys.exit(f'the probe cart failed:\n{r.stdout}{r.stderr}')
    shots = sorted(work.glob('f_*.ppm'))
    try:
        from PIL import Image
    except ImportError:
        print(f'probe: compiled and ran; {len(shots)} frames as PPM in {work}')
        return
    for k, (n, *_rest) in enumerate(views):
        if k < len(shots):
            im = Image.open(shots[k])
            im.resize((im.width*2, im.height*2), Image.NEAREST).save(out/f'{k:02}_{n}.png')
    print(f'probe: compiled and ran; {min(len(shots), len(views))} views in {out}/')


def main():
    dry = '--dry-run' in sys.argv
    check = sys.argv[sys.argv.index('--check')+1] if '--check' in sys.argv else None
    found = recipes()
    skipped, warnings = [], []
    work = Path(tempfile.mkdtemp(prefix='fallline-pack-'))
    try:
        manifest = run_pack(found, work, skipped) if found else None
        semi = {}
        if manifest:
            for _, path in found:
                name, runs, faces = semi_faces(path)
                if runs:
                    mesh = work/f'{name}.bin'
                    mesh.write_bytes(make_semi(mesh.read_bytes(), runs, faces))
                    semi[name] = runs

        lines = [HEADER,
                 '// The pack of every recipe under models/*/ (mei_assets.py pack: texture slots 0-9,',
                 f'// 4-bit palettes from {PALETTE}), and assets_load(), which loads it once. Draw the meshes with the',
                 '// depth test on (render_depth(true), render_perspective(true)).', '']
        if manifest:
            for line in (work/f'{PACK_NAME}.akr').read_text().splitlines():
                lines.append(re.sub(r'^(embed [^=]*= ")([^"]+)"', r'\1art/\2"', line))
            if semi:
                lines += ['', '// Semi-transparent faces (BLEND_HALF), half-open ranges of each mesh\'s faces:']
                for name, runs in semi.items():
                    lines.append(f'//   ASSET_{name.upper()}: '+', '.join(f'{a}-{b}' for a, b in runs)+' (its glass)')
        else:
            lines.append('// No recipes yet.')
        lines += ['', 'fn assets_load() {']
        if manifest:
            lines.append(f'    {PACK_NAME}_load()')
        lines += ['}', '']
        assets_akr = '\n'.join(lines)

        # Totals.
        total = 0
        if manifest:
            print('triangles (README limit):')
            for a in manifest['assets']:
                model = a['name'].split('_')[0]
                limit = LIMITS.get(a['name'], LIMITS.get(model))
                flag = 'OVER   ' if limit and a['triangles'] > limit else '       '
                if limit and a['triangles'] > limit:
                    warnings.append(f'{a["name"]}: {a["triangles"]} triangles, over {limit}')
                ntex = len(a.get('textures', []))
                if ntex > 2:
                    warnings.append(f'{a["name"]}: {ntex} textures, more than 2')
                total += a['triangles']
                print(f'{flag}{a["name"]:12} {a["triangles"]:5}  ({limit if limit else "-"}), '
                      f'{a["vertices"]} vertices, {ntex} textures'
                      + (f', semi-transparent faces {sum(b-a for a, b in semi[a["name"]])}'
                         if a['name'] in semi else ''))
            print(f'       {"total":12} {total:5}')
            tex = manifest.get('textures') or {}
            vram = sum(t['vram_bytes'] for a in manifest['assets'] for t in a.get('textures', []))
            slots = tex.get('slots', [])
            slot_bytes = sum((work/f'{PACK_NAME}.slot{s}.tex').stat().st_size for s in slots)
            print(f'VRAM: {vram} bytes of texels (tiles before de-duplication), slots {slots}, '
                  f'{slot_bytes} bytes loaded')
            pals = set()
            for a in manifest['assets']:
                pals |= set((a.get('palette') or {}).get('palettes', []))
            for run in (tex.get('palettes') or {}).get('runs', []):
                if run['bits'] == 4:
                    pals |= set(range(run['first_colour']//16, (run['first_colour']+run['colours']+15)//16))
                else:
                    warnings.append(f'an 8-bit texture palette (colour {run["first_colour"]}): README asks for 4-bit')
            print(f'palettes: 4-bit {min(pals)}-{max(pals)} ({len(pals)})' if pals else 'palettes: none')
            rom = sum(p.stat().st_size for p in work.iterdir() if p.suffix not in ('.akr', '.json'))
            print(f'ROM: {rom} bytes in art/')
        else:
            print('no recipes yet: assets.akr defines assets_load() only')
        for s in skipped:
            print('SKIPPED', s)
        for w in warnings:
            print('WARNING', w)
        if dry:
            return

        for p in owned_art():
            p.unlink()
        ART.mkdir(exist_ok=True)
        if manifest:
            for p in sorted(work.iterdir()):
                if p.suffix not in ('.akr',):
                    shutil.copy2(p, ART/p.name)
        (CART/'assets.akr').write_text(assets_akr)
        print('wrote carts/fallline/art/ (all but plane_*), carts/fallline/assets.akr')
        if check:
            probe(check, manifest)
    finally:
        shutil.rmtree(work, ignore_errors=True)


if __name__ == '__main__':
    main()
