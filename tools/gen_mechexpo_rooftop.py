def cell_rand(x, y, salt):
    """A repeatable 0..1 for the 8 x 8 cell at (x, y): lit windows without noise per pixel."""
    v = (x // 8) * 73856093 ^ (y // 8) * 19349663 ^ salt * 83492791
    v = (v ^ (v >> 13)) * 1274126177
    return ((v ^ (v >> 16)) & 0xFFFF) / 65536.0


# ---- the city (BG1)

def windows(cv, x0, y0, x1, y1, lit, salt, cols=(W[1], W[0]), dark=None, step=4):
    """Window dots on a building face: rows every `step` px, columns every 4; a cell's windows
    are lit with chance `lit` (all of a cell's together, so tiles repeat)."""
    for y in range(y0 + 2, y1 - 1, step):
        for x in range(x0 + 1, x1 - 1, 4):
            r = cell_rand(x, y, salt)
            if r < lit:
                c = cols[0] if r < lit * 0.75 else cols[1]
                cv.rect(x, y, x + 2, y + 1, c)
            elif dark is not None:
                cv.rect(x, y, x + 2, y + 1, dark)


def tower(cv, x, w, top, base, col, lit, salt, edge=None, crown=None):
    cv.rect(x, top, x + w, base, col)
    if edge:
        cv.rect(x, top, x + 1, base, edge)
    windows(cv, x, top + 3, x + w, base, lit, salt)
    if crown:
        cv.rect(x + w // 2 - 1, top - crown, x + w // 2 + 1, top, col)
        cv.rect(x + w // 2 - 1, top - crown - 1, x + w // 2 + 1, top - crown, WH[0])


def draw_city():
    cv = S.Canvas(CITY_W, CITY_H)
    rng = np.random.default_rng(1970)
    hz = HORIZON
    Wd = CITY_W

    # -- the far skyline (band 0): a long low mass of blocks along the horizon, taller towers in
    # front of it here and there, sparse windows; it wraps every 512 px
    far = N[3]
    x = 0
    while x < Wd:
        w = 8 * int(rng.integers(2, 6))
        h = 8 * int(rng.integers(1, 4))
        cv.rect(x, hz - h, min(x + w, Wd), hz, far)
        windows(cv, x, hz - h, min(x + w, Wd), hz, 0.18, 1, cols=(W[3], N[6]))
        x += w
    # towers (x, width, height): the far city's high-rises
    for tx, tw, th in [(24, 16, 48), (56, 8, 32), (104, 24, 40), (176, 16, 56), (264, 8, 40),
                       (296, 16, 64), (336, 24, 32), (384, 16, 48), (440, 24, 40), (480, 8, 56)]:
        tower(cv, tx, tw, hz - th, hz, N[4], 0.22, 2, edge=N[5], crown=4 if th >= 56 else None)
    # the Umeda Sky Building: two slabs joined at the top by the floating garden's ring
    ux, uy = 208, hz - 80
    cv.rect(ux, uy, ux + 16, hz, N[4])
    cv.rect(ux + 32, uy, ux + 48, hz, N[4])
    cv.rect(ux, uy, ux + 1, hz, N[6])
    cv.rect(ux + 32, uy, ux + 33, hz, N[6])
    windows(cv, ux, uy + 10, ux + 16, hz, 0.3, 3)
    windows(cv, ux + 32, uy + 10, ux + 48, hz, 0.3, 4)
    cv.rect(ux, uy - 2, ux + 48, uy + 8, N[5])                  # the bridge at the top
    cv.ellipse(ux + 14, uy - 10, ux + 34, uy + 8, N[5])          # the ring's opening
    cv.ellipse(ux + 18, uy - 6, ux + 30, uy + 4, H[0])
    cv.rect(ux + 4, uy + 1, ux + 44, uy + 2, W[0])               # the observatory's lights
    cv.rect(ux + 47, uy - 4, ux + 48, uy - 2, WH[0])
    # a lattice tower with a lit crown (Tsutenkaku-like), at x 400
    lx, ly = 408, hz - 72
    for k in range(0, 72, 4):
        y = ly + k
        half = 3 + k // 10
        cv.rect(lx - half, y, lx + half + 1, y + 1, N[5])
        cv.rect(lx - half, y + 1, lx - half + 1, y + 4, N[5])
        cv.rect(lx + half, y + 1, lx + half + 1, y + 4, N[5])
    cv.rect(lx - 6, ly + 20, lx + 7, ly + 26, N[4])              # the observation deck
    cv.rect(lx - 5, ly + 22, lx + 6, ly + 23, U[2])              # its lit band
    cv.rect(lx - 3, ly - 8, lx + 4, ly, N[4])
    cv.rect(lx - 2, ly - 7, lx + 3, ly - 4, U[1])                # the crown's light
    cv.rect(lx, ly - 14, lx + 1, ly - 8, N[5])
    cv.rect(lx, ly - 15, lx + 1, ly - 14, WH[0])
    # HEP's red Ferris wheel on a department store's roof, at x 136
    wx, wy, wr = 144, hz - 40, 18
    cv.rect(wx - 24, hz - 22, wx + 24, hz, N[4])
    windows(cv, wx - 24, hz - 22, wx + 24, hz, 0.35, 5)
    for k in range(32):
        a = k * math.pi * 2 / 32
        px = wx + wr * math.cos(a)
        py = wy + wr * math.sin(a)
        cv.rect(int(px), int(py), int(px) + 2, int(py) + 2, WH[0])
    for k in range(8):
        a = k * math.pi / 4
        cv.line([(wx, wy), (wx + wr * math.cos(a), wy + wr * math.sin(a))], WH[1], 1)
    cv.rect(wx - 1, wy - 1, wx + 2, wy + 2, WH[3])
    cv.line([(wx - 10, hz - 22), (wx, wy)], N[5], 1)
    cv.line([(wx + 10, hz - 22), (wx, wy)], N[5], 1)

    # -- the far city's lights, from the horizon down to the deck's far edge (band 1)
    cv.rect(0, hz, Wd, CITY_LINE, N[1])
    cv.rect(0, hz, Wd, hz + 2, H[3])                             # the glow along the horizon
    for y in range(hz + 3, CITY_LINE, 3):
        k = (y - hz) / (CITY_LINE - hz)
        lit = 0.12 + 0.25 * k
        for x in range(0, Wd, 2):
            r = cell_rand(x * 4 + y, y, 7)
            if r < lit:
                c = W[0] if r < lit * 0.5 else (ST[0] if r < lit * 0.8 else N[7])
                cv.rect(x, y, x + 1, y + 1, c)

    # -- the city at the tower's foot (band 2): rooftops far below, an avenue, neon
    base = CITY_LINE
    cv.rect(0, base, Wd, CITY_H, N[0])
    # blocks of buildings seen from above and the side: roofs, their lit faces
    x = 0
    while x < Wd:
        w = 8 * int(rng.integers(3, 8))
        top = base + 8 * int(rng.integers(1, 6))
        roof = [N[2], N[3], N[2]][int(rng.integers(0, 3))]
        cv.rect(x, top, min(x + w, Wd), top + 6, roof)
        cv.rect(x, top + 6, min(x + w, Wd), CITY_H, N[1])
        windows(cv, x, top + 6, min(x + w, Wd), CITY_H, 0.3, 11, cols=(W[0], W[3]))
        # rooftop plant: an air-conditioning box, a water tank
        if w >= 32:
            cv.rect(x + 6, top - 4, x + 14, top, N[4])
            cv.rect(x + w - 12, top - 6, x + w - 6, top, N[3])
        x += w
    # the avenue: a band of road across, lit both ways
    ay = 222
    cv.rect(0, ay, Wd, ay + 14, N[1])
    cv.rect(0, ay, Wd, ay + 1, N[3])
    cv.rect(0, ay + 13, Wd, ay + 14, N[3])
    for x in range(0, Wd, 16):
        cv.rect(x, ay + 7, x + 8, ay + 8, N[5])                  # the centre line
    for x in range(0, Wd, 6):
        r = cell_rand(x * 8, ay, 13)
        if r < 0.55:
            cv.rect(x, ay + 3, x + 2, ay + 5, ST[2] if r < 0.3 else ST[0])   # headlights
        r = cell_rand(x * 8, ay + 9, 17)
        if r < 0.5:
            cv.rect(x, ay + 9, x + 2, ay + 11, ST[1])            # tail lights
    # street lamps along it
    for x in range(4, Wd, 32):
        cv.rect(x, ay - 6, x + 1, ay, N[5])
        cv.rect(x - 1, ay - 7, x + 3, ay - 6, W[0])
    # neon signs on the buildings' faces: a few vertical bars and boards
    for nx, ny, col in [(40, 178, NE[0]), (120, 190, NE[1]), (232, 172, NE[2]), (312, 186, NE[0]),
                        (376, 176, NE[1]), (456, 192, NE[2])]:
        cv.rect(nx, ny, nx + 6, ny + 24, NE[3] if col is NE[0] else NE[4])
        for k in range(4):
            cv.rect(nx + 1, ny + 2 + k * 6, nx + 5, ny + 5 + k * 6, col)
    for nx, ny in [(168, 200), (400, 204)]:
        cv.rect(nx, ny, nx + 32, ny + 10, NE[4])
        cv.rect(nx + 2, ny + 2, nx + 30, ny + 8, NE[1])
        cv.rect(nx + 4, ny + 4, nx + 28, ny + 6, NE[2])

    pals = [[None] + NIGHT + CITY_ACC[k] for k in CITY_ORDER]
    return cv, pals


def build_city(preview):
    cv, pals = draw_city()
    rgb, alpha = cv.arrays()
    t = S.Tiler(pals, limit=1024)
    m = t.cut(rgb, alpha, 64, 32)
    if preview:
        cv.img.save(os.path.join(preview, 'stage_roof_city.png'))
        S.render_map(t, m, 8, os.path.join(preview, 'stage_roof_city_tiles.png'))
    return t, m


# ---- the deck (BG2)

def draw_deck():
    sz = DECK_N * 8
    fl = DECK_NEUTRAL
    acc = DECK_ACC
    cv = S.Canvas(sz, sz)

    def X(x):
        return int(round(DECK_C + x * DECK_S))

    def Z(z):
        return int(round(DECK_C + z * DECK_S))

    x0, x1 = X(DECK_LEFT), X(ROOF_HALF)
    z0, z1 = X(DECK_NEAR), Z(DECK_FAR)
    # concrete pavers, 2 m, two tones, seams; darker away from the floodlit lane
    P = 2 * DECK_S
    cv.rect(x0, z0, x1, z1, fl[3])
    for j in range(z0, z1, P):
        for i in range(x0 - (x0 % P), x1, P):
            lane = Z(-7) <= j < Z(7)
            a, b = (fl[5], fl[6]) if lane else (fl[3], fl[4])
            cv.rect(max(i, x0), j, min(i + P, x1), min(j + P, z1), b if ((i // P) + (j // P)) & 1 else a)
            cv.rect(max(i, x0), j, min(i + P, x1), j + 1, fl[1])
            if i >= x0:
                cv.rect(i, j, i + 1, min(j + P, z1), fl[1])
    # the showcase lane's edge lines (white), z = -7 and 7, from the stairwell to the hazard band
    edge_in = X(ROOF_HALF - 1.4)
    for z in (-7, 7):
        cv.rect(X(-ROOF_HALF), Z(z) - 1, edge_in, Z(z) + 1, acc['plain'][2])
    # the helipad: a yellow ring (r 9 m) and a white H, centred on the fight's middle
    pad = acc['pad']
    cx, cz = X(0), Z(0)
    r = int(9 * DECK_S)
    cv.ellipse(cx - r, cz - r, cx + r + 1, cz + r + 1, pad[0])
    # the pavers again inside the ring, so the ring is only a band
    inner = Image.new('RGBA', (sz, sz), (0, 0, 0, 0))
    mask = Image.new('L', (sz, sz), 0)
    ImageDraw.Draw(mask).ellipse([cx - r + 4, cz - r + 4, cx + r - 4, cz + r - 4], fill=255)
    lane = S.Canvas(sz, sz)
    for j in range(cz - r, cz + r + P, P):
        for i in range(cx - r - (cx - r) % P, cx + r + P, P):
            a, b = (fl[5], fl[6]) if Z(-7) <= j < Z(7) else (fl[3], fl[4])
            lane.rect(i, j, i + P, j + P, b if ((i // P) + (j // P)) & 1 else a)
            lane.rect(i, j, i + P, j + 1, fl[1])
            lane.rect(i, j, i + 1, j + P, fl[1])
    inner.paste(lane.img, (0, 0), mask)
    cv.img.alpha_composite(inner)
    # the lane's lines again across the pad
    for z in (-7, 7):
        cv.rect(X(-ROOF_HALF), Z(z) - 1, edge_in, Z(z) + 1, acc['plain'][2])
    # the H: 6 m tall (along z), 4 m wide, white, bars 0.9 m
    hw, hh, bw = 2.0, 3.0, 0.9
    cv.rect(X(-hw), Z(-hh), X(-hw + bw), Z(hh), pad[2])
    cv.rect(X(hw - bw), Z(-hh), X(hw), Z(hh), pad[2])
    cv.rect(X(-hw), Z(-bw / 2), X(hw), Z(bw / 2), pad[2])

    # lettering, written to read from the camera (rows run away: flip)
    def deck_text(x, z, s, f, col):
        tmp = Image.new('RGBA', (320, 40), (0, 0, 0, 0))
        td = ImageDraw.Draw(tmp)
        td.fontmode = '1'
        td.text((160, 20), s, font=f, fill=col + (255,), anchor='mm')
        tmp = tmp.transpose(Image.FLIP_TOP_BOTTOM)
        cv.img.alpha_composite(tmp, (X(x) - 160, Z(z) - 20))
    deck_text(0, -10.5, 'UAPC ROOFTOP SHOWCASE', S.font(S.F_BLACK, 16), acc['plain'][2])
    deck_text(0, 11.0, 'EXPO TOWER  //  HELIPAD R1', S.font(S.F_COND, 12), acc['plain'][1])
    # the start marks at x = -9 (1P, red) and 9 (2P, blue)
    st = acc['start']
    for x, col, lab in ((-9, st[0], '1P'), (9, st[1], '2P')):
        cv.rect(X(x) - 12, Z(-3), X(x) + 12, Z(-3) + 3, col)
        cv.rect(X(x) - 12, Z(3) - 3, X(x) + 12, Z(3), col)
        cv.rect(X(x) - 1, Z(-3), X(x) + 1, Z(3), col)
        deck_text(x, -4.4, lab, S.font(S.F_BLACK, 12), st[2])
    # the open edge: a yellow and black hazard band 1.4 m wide inside it, a pale cap at the lip
    hz = acc['hazard']
    hx0 = X(ROOF_HALF - 1.4)
    cv.rect(hx0, z0, x1, z1, hz[1])
    for z in range(z0 - 16, z1, 16):
        cv.poly([(hx0, z), (x1, z + 8), (x1, z + 16), (hx0, z + 8)], hz[0])
    cv.rect(x1 - 2, z0, x1, z1, hz[3])
    cv.rect(hx0, z0, hx0 + 1, z1, hz[2])
    # the far edge: a dark gutter before the parapet
    cv.rect(x0, z1 - 6, x1, z1, fl[1])
    cv.rect(x0, z1 - 7, x1, z1 - 6, fl[7])
    # behind the stairwell (never in view): plain
    pals = [[None] + DECK_NEUTRAL + DECK_ACC[k] for k in DECK_ORDER]
    return cv, pals


def build_deck(preview):
    cv, pals = draw_deck()
    rgb, alpha = cv.arrays()
    t = S.Tiler(pals, limit=1024)
    m = t.cut(rgb, alpha, DECK_N, DECK_N)
    if preview:
        c = DECK_C
        cv.img.crop((c - 40 * DECK_S, c - 26 * DECK_S, c + 34 * DECK_S, c + 34 * DECK_S)).transpose(
            Image.FLIP_TOP_BOTTOM).save(os.path.join(preview, 'stage_roof_deck.png'))
    return t, m


def bgr(s):
    r, g, b = hexc(s)
    return '0x%02X%02X%02X' % (b, g, r)


