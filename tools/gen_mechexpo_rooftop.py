def cell_rand(x, y, salt):
    """A repeatable 0..1 for the 8 x 8 cell at (x, y): lit windows without noise per pixel."""
    v = (x // 8) * 73856093 ^ (y // 8) * 19349663 ^ salt * 83492791
    v = (v ^ (v >> 13)) * 1274126177
    return ((v ^ (v >> 16)) & 0xFFFF) / 65536.0


# ---- the horizon (BG1)

def windows(cv, x0, y0, x1, y1, lit, salt, cols=(W[1], W[0]), dark=None, step=4):
    """Window dots on a building face: rows every `step` px, columns every 4; a cell's windows
    are lit with chance `lit` (all of a cell's together, so tiles repeat)."""
    for y in range(y0 + 2, y1 - 1, step):
        for x in range(x0 + 1, x1 - 1, 4):
            r = cell_rand(x, y, salt)
            if r < lit:
                c = cols[0] if r < lit * 0.75 else cols[1]
                cv.rect(x, y, x + 2, y + 1, c)
            elif dark is not None:
                cv.rect(x, y, x + 2, y + 1, dark)


def draw_city():
    """The far shore and the sea on BG1, behind the city in polygons (props/rooftop_city/):
    across the harbour a low skyline in the haze (the inland city to the left, the bay's far
    shore to the right, flatter and darker, with red lights on its chimneys, then open water),
    the glow along the horizon; below it the sea down to the deck's far edge, its ripples and the
    far lights' long reflections; and below that, past the open edge, the harbour's water seen
    from above (what the polygons' quay does not cover). Everything near enough to have sides is
    a polygon; this is what is too far to have any."""
    cv = S.Canvas(CITY_W, CITY_H)
    rng = np.random.default_rng(1989)
    hz = HORIZON
    Wd = CITY_W
    lights = []                                  # (x, colour) of the shore's lights, reflected below

    # -- the far shore (band 0): wraps every 512 px; art column 256 is world x = 0 (the fight's
    # middle). Inland (left of ~250) a low city mass with a few taller blocks; past it the
    # harbour's far side, lower; right of ~330 the bay's far shore, a thin dark line with sparse
    # lights and red chimney lights; right of ~450 open water to the horizon
    far, farther = H[3], H[1]
    x = 0
    while x < Wd:
        if x < 250:
            w, h = 8 * int(rng.integers(2, 5)), 2 * int(rng.integers(2, 7))
        elif x < 330:
            w, h = 8 * int(rng.integers(2, 5)), 2 * int(rng.integers(1, 4))
        elif x < 450:
            w, h = 8 * int(rng.integers(3, 7)), int(rng.integers(1, 4))
        else:
            w, h = 8, 0
        x1 = min(x + w, Wd)
        if h:
            cv.rect(x, hz - h, x1, hz, farther if h > 9 else far)
            for wx in range(x + 1, x1 - 1, 3):
                for wy in range(hz - h + 1, hz, 3):
                    r = cell_rand(wx, wy, 3)
                    if r < 0.10:
                        cv.rect(wx, wy, wx + 1, wy + 1, H[4] if r < 0.06 else W[1])
                        if wy >= hz - 4 and r < 0.06:
                            lights.append((wx, W[0]))
        x = x1
    for tx, tw, th in [(40, 8, 20), (72, 16, 16), (136, 8, 22), (200, 16, 14), (280, 8, 10)]:
        cv.rect(tx, hz - th, tx + tw, hz, farther)
        cv.rect(tx, hz - th, tx + 1, hz, H[0])
        windows(cv, tx, hz - th + 3, tx + tw, hz, 0.16, 2, cols=(H[4], H[0]))
        cv.rect(tx + tw // 2, hz - th - 2, tx + tw // 2 + 1, hz - th - 1, SC[4])
    for cx in (352, 371, 404, 428):                                  # chimneys with red lights
        h = 7 + (cx % 5)
        cv.rect(cx, hz - h, cx + 1, hz, farther)
        cv.rect(cx, hz - h - 1, cx + 1, hz - h, SC[4])
        lights.append((cx, SC[4]))
    for x in range(336, 448, 5):                                     # the shore's lamps
        r = cell_rand(x * 3, hz, 5)
        if r < 0.55:
            cv.rect(x, hz - 1, x + 1, hz, W[0] if r < 0.35 else SC[3])
            lights.append((x, W[0] if r < 0.35 else SC[3]))

    # -- the moon: 2000-10-12 was the eve of a full moon, rising in the east over the bay at
    # the blue hour: a disc low above the far shore, and its glade on the sea below (drawn last)
    mx, my, mr = MOON
    cv.ellipse(mx - mr, my - mr, mx + mr + 1, my + mr + 1, W[2])

    # -- the sea (band 1), from the horizon to the deck's far edge: the glow's reflection just
    # under the horizon, thin ripples (closer together toward the horizon) and long broken
    # reflections under the shore's lights
    cv.rect(0, hz, Wd, CITY_LINE, SEA[0])
    for x in range(0, Wd, 2):
        if cell_rand(x * 5, hz, 9) < 0.7:
            cv.rect(x, hz, x + 2, hz + 1, H[3])
        if cell_rand(x * 7, hz + 1, 9) < 0.35:
            cv.rect(x, hz + 1, x + 2, hz + 2, H[3])
    y = hz + 3
    gap = 2
    while y < CITY_LINE:
        for x in range(0, Wd, 4):
            r = cell_rand(x * 11 + y, y, 21)
            if r < 0.30:
                cv.rect(x, y, x + 2 + int(r * 10) % 3, y + 1, SEA[2] if r < 0.06 else SEA[1])
        y += gap
        gap = min(gap + 1, 3) if y > hz + 8 else gap
    for lx, col in lights:
        n = 5 + int(cell_rand(lx * 13, hz, 23) * 10)
        for j in range(n):
            if cell_rand(lx * 17 + j, hz + j, 29) < 0.55 - 0.03 * j:
                cv.rect(lx, hz + 1 + j, lx + 1, hz + 2 + j, col if j < 3 or col != W[0] else W[1])

    for j in range(CITY_LINE - hz - 1):                              # the moon's glade
        half = 1 + j // 6
        for x in range(mx - half, mx + half + 1, 2):
            if cell_rand(x * 19 + j, hz + j, 37) < 0.62 - 0.012 * j:
                cv.rect(x, hz + 1 + j, x + 2, hz + 2 + j, W[2] if j < 6 or (x + j) % 3 else W[0])

    # -- the harbour past the open edge (band 2): dark water, ripples every few rows (closer
    # together far off, at the top), a few cool glints; a pattern that repeats every 32 px so
    # its tiles repeat
    base = CITY_LINE
    cv.rect(0, base, Wd, CITY_H, SEA[0])
    y = base + 1
    k = 0
    while y < CITY_H:
        gap = 2 if y < base + 24 else 3 if y < base + 56 else 4
        for x0 in range(0, 32, 8):
            r = cell_rand(x0 * 7 + k * 3, y, 31)
            if r < 0.55:
                ln = 2 + int(r * 9) % 4
                for rep in range(0, Wd, 32):
                    cv.rect(rep + x0 + (k * 3) % 5, y, rep + x0 + (k * 3) % 5 + ln, y + 1,
                            SC[3] if r < 0.03 else SEA[2] if r < 0.12 else SEA[1])
        y += gap
        k += 1

    pals = [[None] + NIGHT + CITY_ACC[k] for k in CITY_ORDER]
    return cv, pals


def build_city(preview):
    cv, pals = draw_city()
    rgb, alpha = cv.arrays()
    t = S.Tiler(pals, limit=1024)
    m = t.cut(rgb, alpha, 64, 32)
    if preview:
        cv.img.save(os.path.join(preview, 'stage_roof_city.png'))
        S.render_map(t, m, 8, os.path.join(preview, 'stage_roof_city_tiles.png'))
    return t, m


# ---- the deck (BG2)

def draw_deck():
    sz = DECK_N * 8
    fl = DECK_NEUTRAL
    acc = DECK_ACC
    cv = S.Canvas(sz, sz)

    def X(x):
        return int(round(DECK_C + x * DECK_S))

    def Z(z):
        return int(round(DECK_C + z * DECK_S))

    x0, x1 = X(DECK_LEFT), X(ROOF_HALF)
    z0, z1 = X(DECK_NEAR), Z(DECK_FAR)
    # concrete pavers, 2 m, two tones, seams; darker away from the floodlit lane
    P = 2 * DECK_S
    cv.rect(x0, z0, x1, z1, fl[3])
    for j in range(z0, z1, P):
        for i in range(x0 - (x0 % P), x1, P):
            lane = Z(-7) <= j < Z(7)
            a, b = (fl[5], fl[6]) if lane else (fl[3], fl[4])
            cv.rect(max(i, x0), j, min(i + P, x1), min(j + P, z1), b if ((i // P) + (j // P)) & 1 else a)
            cv.rect(max(i, x0), j, min(i + P, x1), j + 1, fl[1])
            if i >= x0:
                cv.rect(i, j, i + 1, min(j + P, z1), fl[1])
    # the showcase lane's edge lines (white), z = -7 and 7, from the stairwell to the hazard band
    edge_in = X(ROOF_HALF - 1.4)
    for z in (-7, 7):
        cv.rect(X(-ROOF_HALF), Z(z) - 1, edge_in, Z(z) + 1, acc['plain'][2])
    # the helipad: a yellow ring (r 9 m) and a white H, centred on the fight's middle
    pad = acc['pad']
    cx, cz = X(0), Z(0)
    r = int(9 * DECK_S)
    cv.ellipse(cx - r, cz - r, cx + r + 1, cz + r + 1, pad[0])
    # the pavers again inside the ring, so the ring is only a band
    inner = Image.new('RGBA', (sz, sz), (0, 0, 0, 0))
    mask = Image.new('L', (sz, sz), 0)
    ImageDraw.Draw(mask).ellipse([cx - r + 4, cz - r + 4, cx + r - 4, cz + r - 4], fill=255)
    lane = S.Canvas(sz, sz)
    for j in range(cz - r, cz + r + P, P):
        for i in range(cx - r - (cx - r) % P, cx + r + P, P):
            a, b = (fl[5], fl[6]) if Z(-7) <= j < Z(7) else (fl[3], fl[4])
            lane.rect(i, j, i + P, j + P, b if ((i // P) + (j // P)) & 1 else a)
            lane.rect(i, j, i + P, j + 1, fl[1])
            lane.rect(i, j, i + 1, j + P, fl[1])
    inner.paste(lane.img, (0, 0), mask)
    cv.img.alpha_composite(inner)
    # the lane's lines again across the pad
    for z in (-7, 7):
        cv.rect(X(-ROOF_HALF), Z(z) - 1, edge_in, Z(z) + 1, acc['plain'][2])
    # the H: 6 m tall (along z), 4 m wide, white, bars 0.9 m
    hw, hh, bw = 2.0, 3.0, 0.9
    cv.rect(X(-hw), Z(-hh), X(-hw + bw), Z(hh), pad[2])
    cv.rect(X(hw - bw), Z(-hh), X(hw), Z(hh), pad[2])
    cv.rect(X(-hw), Z(-bw / 2), X(hw), Z(bw / 2), pad[2])

    # lettering, written to read from the camera (rows run away: flip)
    def deck_text(x, z, s, f, col):
        tmp = Image.new('RGBA', (320, 40), (0, 0, 0, 0))
        td = ImageDraw.Draw(tmp)
        td.fontmode = '1'
        td.text((160, 20), s, font=f, fill=col + (255,), anchor='mm')
        tmp = tmp.transpose(Image.FLIP_TOP_BOTTOM)
        cv.img.alpha_composite(tmp, (X(x) - 160, Z(z) - 20))
    deck_text(0, -10.5, 'UAPC ROOFTOP SHOWCASE', S.font(S.F_BLACK, 16), acc['plain'][2])
    deck_text(0, 11.0, 'EXPO TOWER  //  HELIPAD R1', S.font(S.F_COND, 12), acc['plain'][1])
    # the start marks at x = -9 (1P, red) and 9 (2P, blue)
    st = acc['start']
    for x, col, lab in ((-9, st[0], '1P'), (9, st[1], '2P')):
        cv.rect(X(x) - 12, Z(-3), X(x) + 12, Z(-3) + 3, col)
        cv.rect(X(x) - 12, Z(3) - 3, X(x) + 12, Z(3), col)
        cv.rect(X(x) - 1, Z(-3), X(x) + 1, Z(3), col)
        deck_text(x, -4.4, lab, S.font(S.F_BLACK, 12), st[2])
    # the open edge: a yellow and black hazard band 1.4 m wide inside it, a pale cap at the lip
    hz = acc['hazard']
    hx0 = X(ROOF_HALF - 1.4)
    cv.rect(hx0, z0, x1, z1, hz[1])
    for z in range(z0 - 16, z1, 16):
        cv.poly([(hx0, z), (x1, z + 8), (x1, z + 16), (hx0, z + 8)], hz[0])
    cv.rect(x1 - 2, z0, x1, z1, hz[3])
    cv.rect(hx0, z0, hx0 + 1, z1, hz[2])
    # the far edge: a dark gutter before the parapet
    cv.rect(x0, z1 - 6, x1, z1, fl[1])
    cv.rect(x0, z1 - 7, x1, z1 - 6, fl[7])
    # behind the stairwell (never in view): plain
    pals = [[None] + DECK_NEUTRAL + DECK_ACC[k] for k in DECK_ORDER]
    return cv, pals


def build_deck(preview):
    cv, pals = draw_deck()
    rgb, alpha = cv.arrays()
    t = S.Tiler(pals, limit=1024)
    m = t.cut(rgb, alpha, DECK_N, DECK_N)
    if preview:
        c = DECK_C
        cv.img.crop((c - 40 * DECK_S, c - 26 * DECK_S, c + 34 * DECK_S, c + 34 * DECK_S)).transpose(
            Image.FLIP_TOP_BOTTOM).save(os.path.join(preview, 'stage_roof_deck.png'))
    return t, m


def bgr(s):
    r, g, b = hexc(s)
    return '0x%02X%02X%02X' % (b, g, r)


