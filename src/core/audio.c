/* Audio: sixteen sample channels (8-bit, 16-bit or 4-bit ADPCM) and a global reverb,
 * mixed to 22,050 Hz stereo, integer-only. docs/DECISIONS.md ("Audio upgrade") is the reference. */
#include "machine.h"

#include <string.h>

/* floor(x / 2^s) without relying on implementation-defined >> of negatives. */
static inline int32_t asr8(int32_t x) { return x >= 0 ? x >> 8 : ~((~x) >> 8); }
static inline int64_t asr64(int64_t x, int s) { return x >= 0 ? x >> s : ~((~x) >> s); }
/* x / 2^15 rounded toward zero: what every feedback product in the reverb uses, so a
 * silent reverb always decays to exactly zero. */
static inline int32_t q15t(int64_t x) { return (int32_t)(x >= 0 ? x >> 15 : -((-x) >> 15)); }
static inline int32_t clampi(int64_t x, int32_t lim) { return (int32_t)(x < -lim ? -lim : x > lim ? lim : x); }

/* ------------------------------------------------------------------ reverb presets */

/* Presets 1-4 are an 8-line feedback delay network: predelay, four Schroeder allpass
 * diffusers, then eight delay lines, each with a one-pole damping filter and a gain, mixed
 * by an 8x8 Hadamard matrix. Gains and damping follow Jot's absorbent-filter design for the
 * RT60 and high-frequency ratio below; tools/gen_reverb_tables.py computes them. Preset 5
 * is a ping-pong echo on lines 0-1. All values are Q15. */
typedef struct {
    uint16_t pre;          /* predelay, samples (>= 1) */
    uint16_t ap[4];        /* diffuser allpass delays */
    int32_t ap_g;          /* diffuser coefficient */
    uint16_t len[8];       /* delay line lengths */
    int32_t damp[8];       /* damping filter coefficient a: lp += a (x - lp) */
    int32_t gain[8];       /* loop gain (FDN: includes the matrix's 1/sqrt(8)) */
    int32_t out;           /* output gain */
    int echo;
} RevPreset;

